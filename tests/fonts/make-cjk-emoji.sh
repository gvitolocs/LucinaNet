#!/bin/sh
# Writes tests/fonts/cjk-emoji.html, the CJK and emoji font test page of font-test.
#   tests/fonts/make-cjk-emoji.sh [out.html]      (default: cjk-emoji.html beside this script)
# Portable sh (Mac bash 3.2 and BSD tools): no GNU-only flags. Every cell is one test character (or one
# sequence) in a fixed 96 px cell; its code points are in its data-cp attribute so tools/font-tofu-check can
# map a cell back to a character. A block is a <section data-block=...>; data-control marks the blocks that
# are controls (Latin, Cyrillic, Greek, Arabic, Devanagari: they must draw on any host), data-ref the two
# TOFU REFERENCE cells (U+FFFF and U+10FFFF, code points no font assigns, which every engine draws as its
# notdef glyph). A spec is code points in hex joined by +, e.g. 1F468+200D+1F469.
set -eu
here=$(cd "$(dirname "$0")" && pwd)
out=${1:-$here/cjk-emoji.html}

cell() {  # $1 = spec
    spec=$1
    chars=""
    oldifs=$IFS
    IFS=+
    for cp in $spec; do
        chars="$chars&#x$cp;"
    done
    IFS=$oldifs
    printf '<b data-cp="U+%s">%s</b>\n' "$spec" "$chars"
}

block() {  # $1 = title, $2 = kind (test|control), then the specs
    title=$1
    kind=$2
    shift 2
    flag=""
    [ "$kind" = control ] && flag=' data-control="1"'
    printf '<section data-block="%s"%s>\n<h2>%s</h2>\n<div class="g">\n' "$title" "$flag" "$title"
    for spec in "$@"; do
        cell "$spec"
    done
    printf '</div>\n</section>\n'
}

