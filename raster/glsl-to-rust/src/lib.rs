/// The parameters of a function variant (`mut p: T`, `p: &mut T` for out/inout), with `ctx` first and
/// `_cond_mask_` last as needed.
fn show_function_prototype(state: &OutputState, fd: &hir::FunctionDefinition, sym: SymRef) -> String {
    let fp = &fd.prototype;
    let info = state.info(sym);
    let mut s = String::new();
    let _ = write!(s, "fn {}(&{}self", state.fn_name(sym, state.vector_mask), if info.mut_self { "mut " } else { "" });
    if info.needs_ctx {
        s.push_str(", ctx: &mut RasterState");
    }
    for p in &fp.parameters {
        match p {
            hir::FunctionParameterDeclaration::Named(qual, fpd) => {
                let scalar = symbol_run_class(&state.hir.sym(fpd.sym).decl, state.vector_mask) == hir::RunClass::Scalar;
                let ty = type_name(state, &fpd.ty, scalar);
                match qual {
                    Some(hir::ParameterQualifier::Out) | Some(hir::ParameterQualifier::InOut) => {
                        let _ = write!(s, ", {}: &mut {}", rust_ident(fpd.name.as_str()), ty);
                    }
                    _ => {
                        let _ = write!(s, ", mut {}: {}", rust_ident(fpd.name.as_str()), ty);
                    }
                }
            }
            // `main(void)`
            hir::FunctionParameterDeclaration::Unnamed(_, ty)
                if matches!(ty.ty, syntax::TypeSpecifierNonArray::Void) => {}
            hir::FunctionParameterDeclaration::Unnamed(..) => panic!("unnamed parameter"),
        }
    }
    if (state.vector_mask & (1 << 31)) != 0 {
        let _ = write!(s, ", _cond_mask_: {}", state.rt("glsl", "I32"));
    }
    s.push(')');
    if fp.ty.kind != TypeKind::Void {
        let _ = write!(s, " -> {}", type_name(state, &fp.ty, !state.return_vector));
    }
    s
}

// This is a hack to run through the first time with an empty writter to find if 'return' is declared.
fn has_conditional_return(state: &mut OutputState, cst: &hir::CompoundStatement) -> bool {
    let buffer = state.push_buffer();
    let breaks = state.breaks.replace(Vec::new());
    show_compound_statement(state, cst);
    state.breaks.replace(breaks);
    state.pop_buffer(buffer);
    let result = state.return_declared;
    state.return_declared = false;
    result
}

fn is_return(s: &hir::Statement) -> bool {
    match s {
        hir::Statement::Simple(s) => matches!(**s, hir::SimpleStatement::Jump(hir::JumpStatement::Return(_))),
        hir::Statement::Compound(c) => c.statement_list.last().is_some_and(is_return),
    }
}

fn show_function_definition(state: &mut OutputState, fd: &hir::FunctionDefinition, sym: SymRef, vector_mask: u32) {
    let is_main = fd.prototype.name.as_str() == "main";
    // `pattern_fragment` is the fragment entry `main` calls once per chunk; swgl's clang inlines it into
    // `run`/`run_perspective`, so the Rust must too (raster/PERF.md round 11).
    let is_pattern_fragment = fd.prototype.name.as_str() == "pattern_fragment";
    {
        let mut out_params = state.out_params.borrow_mut();
        out_params.clear();
        for p in &fd.prototype.parameters {
            if let hir::FunctionParameterDeclaration::Named(
                Some(hir::ParameterQualifier::Out) | Some(hir::ParameterQualifier::InOut),
                fpd,
            ) = p
            {
                out_params.insert(fpd.sym);
            }
        }
    }
    state.tmp_index.set(0);
    show_indent(state);
    if is_main || is_pattern_fragment {
        state.write("#[inline(always)]\n");
        show_indent(state);
    }
    let proto = show_function_prototype(state, fd, sym);
    state.write(&proto);
    state.write(" {\n");
    state.return_type = Some(Box::new(fd.prototype.ty.clone()));

    if (vector_mask & (1 << 31)) != 0 {
        state.mask =
            Some(Box::new(hir::Expr { kind: hir::ExprKind::CondMask, ty: hir::Type::new(hir::TypeKind::Bool) }));
    }

    state.indent();
    let saved_index = state.cond_index;
    let returns = has_conditional_return(state, &fd.body);
    let _ = saved_index;
    if returns {
        show_indent(state);
        let init = if let Some(mask) = &state.mask {
            show_hir_expr(state, mask)
        } else if state.return_vector {
            format!("{}::from(!0i32)", state.rt("glsl", "I32"))
        } else {
            "!0i32".to_string()
        };
        writeln!(state, "let mut ret_mask: {} = {};", ret_mask_type(state), init);
        if fd.prototype.ty != Type::new(hir::TypeKind::Void) {
            show_indent(state);
            let ty = type_name(state, &fd.prototype.ty, !state.return_vector);
            writeln!(state, "let mut ret: {} = Default::default();", ty);
        }
    }

    // swgl_drawSpan*: undo the span shader's changes to the interpolants on the way out, as C++'s `_Undo_`.
    let mut needs_undo = vec![];
    if matches!(fd.prototype.name.as_str(), "swgl_drawSpanRGBA8" | "swgl_drawSpanR8") {
        for global in &fd.globals {
            let sym = state.hir.sym(*global);
            if let hir::SymDecl::Global(hir::StorageClass::In, _, _, hir::RunClass::Vector) = &sym.decl {
                needs_undo.push(sym.name.clone());
            }
        }
    }
    if !needs_undo.is_empty() {
        for name in &needs_undo {
            show_indent(state);
            writeln!(state, "let _undo_{0}_ = self.{0};", name);
        }
        show_indent(state);
        state.write("'body: {\n");
        state.indent();
    }

    {
        let mut texel_fetches = state.texel_fetches.borrow_mut();
        texel_fetches.clear();
        let mut fetches: Vec<_> = fd.texel_fetches.iter().collect();
        fetches.sort_by_key(|((s, b), _)| (state.hir.sym(*s).name.clone(), state.hir.sym(*b).name.clone()));
        for ((sampler, base), offsets) in fetches {
            add_used_global(state, sampler);
            let sampler_sym = state.hir.sym(*sampler);
            let base_sym = state.hir.sym(*base);
            match &base_sym.decl {
                hir::SymDecl::Global(..) => {
                    add_used_global(state, base);
                    define_texel_fetch_ptr(state, &base_sym, &sampler_sym, offsets);
                }
                hir::SymDecl::Local(..) => {
                    if fd.prototype.has_parameter(*base) {
                        define_texel_fetch_ptr(state, &base_sym, &sampler_sym, offsets);
                    } else {
                        texel_fetches.push((*sampler, *base, offsets.clone()));
                    }
                }
                _ => panic!(),
            }
        }
    }

    let undo_body = !needs_undo.is_empty();
    if undo_body {
        state.breaks.borrow_mut().push(Brk::Body);
    }
    for st in &fd.body.statement_list {
        show_statement(state, st);
    }
    if undo_body {
        state.breaks.borrow_mut().pop();
        state.outdent();
        show_indent(state);
        state.write("}\n");
        for name in &needs_undo {
            show_indent(state);
            writeln!(state, "self.{0} = _undo_{0}_;", name);
        }
    }

    if state.return_declared {
        show_indent(state);
        if fd.prototype.ty == Type::new(hir::TypeKind::Void) {
            state.write("return;\n");
        } else {
            state.write("return ret;\n");
        }
    } else if fd.prototype.ty.kind != TypeKind::Void && !fd.body.statement_list.last().is_some_and(is_return) {
        // Every path returned in GLSL; Rust wants a value at the end (unreachable, like the C++'s fall-off).
        show_indent(state);
        state.write("#[allow(unreachable_code)]\n");
        show_indent(state);
        state.write("Default::default()\n");
    }
    state.outdent();

    show_indent(state);
    state.write("}\n");

    state.return_type = None;
    state.return_declared = false;
    state.mask = None;
    state.out_params.borrow_mut().clear();
}

fn show_compound_statement(state: &mut OutputState, cst: &hir::CompoundStatement) {
    show_indent(state);
    state.write("{\n");

    state.indent();
    for st in &cst.statement_list {
        show_statement(state, st);
    }
    state.outdent();

    show_indent(state);
    state.write("}\n");
}

fn show_statement(state: &mut OutputState, st: &hir::Statement) {
    match *st {
        hir::Statement::Compound(ref cst) => show_compound_statement(state, cst),
        hir::Statement::Simple(ref sst) => show_simple_statement(state, sst),
    }
}

fn show_simple_statement(state: &mut OutputState, sst: &hir::SimpleStatement) {
    match *sst {
        hir::SimpleStatement::Declaration(ref d) => show_declaration(state, d),
        hir::SimpleStatement::Expression(ref e) => show_expression_statement(state, e),
        hir::SimpleStatement::Selection(ref s) => show_selection_statement(state, s),
        hir::SimpleStatement::Switch(ref s) => show_switch_statement(state, s),
        hir::SimpleStatement::Iteration(ref i) => show_iteration_statement(state, i),
        hir::SimpleStatement::Jump(ref j) => show_jump_statement(state, j),
    }
}

fn show_indent(state: &OutputState) {
    for _ in 0..state.indent {
        state.write("    ");
    }
}

fn show_expression_statement(state: &mut OutputState, est: &hir::ExprStatement) {
    if let Some(ref e) = *est {
        show_indent(state);
        let code = ex_inner(state, e, true);
        state.write(&code);
        state.write(";\n");
    }
}

fn show_selection_statement(state: &mut OutputState, sst: &hir::SelectionStatement) {
    show_indent(state);

    if state.return_declared || is_vec(state, &sst.cond) {
        let (cond_index, mask) = if state.mask.is_none() || sst.else_stmt.is_some() {
            let cond = sst.cond.clone();
            state.cond_index += 1;
            let cond_index = state.cond_index;
            let code = show_hir_expr(state, &cond);
            writeln!(state, "let mut _c{}_ = {};", cond_index, code);
            (
                cond_index,
                Box::new(hir::Expr {
                    kind: hir::ExprKind::Cond(cond_index, cond),
                    ty: hir::Type::new(hir::TypeKind::Bool),
                }),
            )
        } else {
            (0, sst.cond.clone())
        };

        let previous = state.mask.take();
        state.mask = Some(match previous.clone() {
            Some(e) => {
                let cond = Box::new(hir::Expr {
                    kind: hir::ExprKind::Binary(syntax::BinaryOp::BitAnd, e, mask.clone()),
                    ty: hir::Type::new(hir::TypeKind::Bool),
                });
                state.cond_index += 1;
                let nested_cond_index = state.cond_index;
                show_indent(state);
                let code = show_hir_expr(state, &cond);
                writeln!(state, "let mut _c{}_ = {};", nested_cond_index, code);
                Box::new(hir::Expr {
                    kind: hir::ExprKind::Cond(nested_cond_index, cond),
                    ty: hir::Type::new(hir::TypeKind::Bool),
                })
            }
            None => mask.clone(),
        });

        show_statement(state, &sst.body);
        state.mask = previous;

        if let Some(rest) = &sst.else_stmt {
            // invert the condition
            let inverted_cond = Box::new(hir::Expr {
                kind: hir::ExprKind::Unary(UnaryOp::Complement, mask),
                ty: hir::Type::new(hir::TypeKind::Bool),
            });
            let previous = state.mask.take();
            state.mask = Some(match previous.clone() {
                Some(e) => {
                    let cond = Box::new(hir::Expr {
                        kind: hir::ExprKind::Binary(syntax::BinaryOp::BitAnd, e, inverted_cond),
                        ty: hir::Type::new(hir::TypeKind::Bool),
                    });
                    show_indent(state);
                    let code = show_hir_expr(state, &cond);
                    writeln!(state, "_c{}_ = {};", cond_index, code);
                    Box::new(hir::Expr {
                        kind: hir::ExprKind::Cond(cond_index, cond),
                        ty: hir::Type::new(hir::TypeKind::Bool),
                    })
                }
                None => inverted_cond,
            });

            show_statement(state, rest);
            state.mask = previous;
        }
    } else {
        let cond = ex_to(state, &sst.cond, &Type::new(TypeKind::Bool), false);
        writeln!(state, "if {} {{", cond);

        state.indent();
        show_statement(state, &sst.body);
        state.outdent();

        show_indent(state);
        if let Some(rest) = &sst.else_stmt {
            state.write("} else {\n");
            state.indent();
            show_statement(state, rest);
            state.outdent();
            show_indent(state);
            state.write("}\n");
        } else {
            state.write("}\n");
        }
    }
}

fn case_stmts_to_if_stmts(stmts: &[Statement], last: bool) -> (Option<Box<Statement>>, bool) {
    // Look for jump statements and remove them
    // We currently are pretty strict on the form that the statement
    // list needs to be in. This can be loosened as needed.
    let mut fallthrough = false;
    let cstmt = match stmts {
        [hir::Statement::Compound(c)] => match c.statement_list.split_last() {
            Some((hir::Statement::Simple(s), rest)) => match **s {
                hir::SimpleStatement::Jump(hir::JumpStatement::Break) => {
                    hir::CompoundStatement { statement_list: rest.to_owned() }
                }
                _ => panic!("fall through not supported"),
            },
            _ => panic!("empty compound"),
        },
        [hir::Statement::Simple(s)] => {
            match **s {
                hir::SimpleStatement::Jump(hir::JumpStatement::Break) => {
                    hir::CompoundStatement { statement_list: Vec::new() }
                }
                _ => {
                    if last {
                        // we don't need a break at the end
                        hir::CompoundStatement { statement_list: vec![hir::Statement::Simple(s.clone())] }
                    } else {
                        panic!("fall through not supported {:?}", s)
                    }
                }
            }
        }
        [] => return (None, true),
        stmts => match stmts.split_last() {
            Some((hir::Statement::Simple(s), rest)) => match **s {
                hir::SimpleStatement::Jump(hir::JumpStatement::Break) => {
                    hir::CompoundStatement { statement_list: rest.to_owned() }
                }
                _ => {
                    if !last {
                        fallthrough = true;
                    }
                    hir::CompoundStatement { statement_list: stmts.to_owned() }
                }
            },
            _ => panic!("unexpected empty"),
        },
    };
    let stmts = Box::new(hir::Statement::Compound(Box::new(cstmt)));
    (Some(stmts), fallthrough)
}

// glsl-to-cxx's signature, kept.
#[allow(clippy::borrowed_box)]
fn build_selection<'a, I: Iterator<Item = &'a hir::Case>>(
    head: &Box<hir::Expr>,
    case: &hir::Case,
    mut cases: I,
    default: Option<&hir::Case>,
    previous_condition: Option<Box<hir::Expr>>,
    previous_stmts: Option<Box<hir::Statement>>,
) -> hir::SelectionStatement {
    let cond = match &case.label {
        hir::CaseLabel::Case(e) => Some(Box::new(hir::Expr {
            kind: hir::ExprKind::Binary(syntax::BinaryOp::Equal, head.clone(), e.clone()),
            ty: hir::Type::new(hir::TypeKind::Bool),
        })),
        hir::CaseLabel::Def => None,
    };

    // if we have two conditions join them
    let cond = match (&previous_condition, &cond) {
        (Some(prev), Some(cond)) => Some(Box::new(hir::Expr {
            kind: hir::ExprKind::Binary(syntax::BinaryOp::Or, prev.clone(), cond.clone()),
            ty: hir::Type::new(hir::TypeKind::Bool),
        })),
        (_, cond) => cond.clone(),
    };

    let (cond, body, else_stmt) = match (cond, cases.next()) {
        (None, Some(next_case)) => {
            assert!(previous_stmts.is_none());
            // default so just move on to the next
            return build_selection(head, next_case, cases, default, None, None);
        }
        (Some(cond), Some(next_case)) => {
            assert!(previous_stmts.is_none());
            let (stmts, fallthrough) = case_stmts_to_if_stmts(&case.stmts, false);
            if let (false, Some(body)) = (fallthrough, stmts.clone()) {
                (
                    cond,
                    body,
                    Some(Box::new(hir::Statement::Simple(Box::new(hir::SimpleStatement::Selection(build_selection(
                        head, next_case, cases, default, None, None,
                    )))))),
                )
            } else {
                // empty so fall through to the next
                return build_selection(head, next_case, cases, default, Some(cond), stmts);
            }
        }
        (Some(cond), None) => {
            // non-default last
            assert!(previous_stmts.is_none());
            let (stmts, _) = case_stmts_to_if_stmts(&case.stmts, default.is_none());
            let stmts = stmts.expect("empty case labels unsupported at the end");
            // add the default case at the end if we have one
            (
                cond,
                stmts,
                match default {
                    Some(default) => {
                        let (default_stmts, fallthrough) = case_stmts_to_if_stmts(&default.stmts, true);
                        assert!(!fallthrough);
                        Some(default_stmts.expect("empty default unsupported"))
                    }
                    None => None,
                },
            )
        }
        (None, None) => {
            // default, last

            assert!(default.is_some());

            let (stmts, fallthrough) = case_stmts_to_if_stmts(&case.stmts, true);
            let stmts = stmts.expect("empty default unsupported");
            assert!(!fallthrough);

            match previous_stmts {
                Some(previous_stmts) => {
                    let cond = previous_condition.expect("must have previous condition");
                    (cond, previous_stmts, Some(stmts))
                }
                None => {
                    let cond = Box::new(hir::Expr {
                        kind: hir::ExprKind::BoolConst(true),
                        ty: hir::Type::new(hir::TypeKind::Bool),
                    });
                    (cond, stmts, None)
                }
            }
        }
    };

    hir::SelectionStatement { cond, body, else_stmt }
}

fn lower_switch_to_ifs(sst: &hir::SwitchStatement) -> hir::SelectionStatement {
    let default = sst.cases.iter().find(|x| x.label == hir::CaseLabel::Def);
    let mut cases = sst.cases.iter();
    build_selection(&sst.head, cases.next().unwrap(), cases, default, None, None)
}

/// Whether a statement list can fall off its end into the next case.
fn falls_through(stmts: &[Statement]) -> bool {
    match stmts.last() {
        None => true,
        Some(hir::Statement::Simple(s)) => !matches!(
            **s,
            hir::SimpleStatement::Jump(
                hir::JumpStatement::Break | hir::JumpStatement::Return(_) | hir::JumpStatement::Continue
            )
        ),
        Some(hir::Statement::Compound(c)) => falls_through(&c.statement_list),
    }
}

/// A scalar `switch` is a labeled block holding an `if`/`else if` chain on the head (the default last), so that a
/// `break` anywhere in a case leaves the switch (`break 'swN`) and not an enclosing loop. Runs of labels sharing
/// one body are joined with `||`; a case that falls through into the next body is not supported (glsl-to-cxx
/// supports it only for vector switches, through `lower_switch_to_ifs`).
fn show_switch_statement(state: &mut OutputState, sst: &hir::SwitchStatement) {
    if is_vec(state, &sst.head) {
        // XXX: when lowering switches we end up with a mask that has
        // a bunch of mutually exclusive conditions.
        // It would be nice if we could fold them together.
        let ifs = lower_switch_to_ifs(sst);
        return show_selection_statement(state, &ifs);
    }

    let label = state.label_index.get();
    state.label_index.set(label + 1);
    let head = ex(state, &sst.head);
    let head_ty = sst.head.ty.clone();
    show_indent(state);
    writeln!(state, "'sw{}: {{", label);
    state.indent();
    show_indent(state);
    writeln!(state, "let _sw{}_: {} = {};", label, type_name(state, &head_ty, true), head);

    // Group the cases: labels with no statements share the next body.
    let mut groups: Vec<(Vec<Option<String>>, &[Statement])> = Vec::new();
    let mut pending: Vec<Option<String>> = Vec::new();
    for case in &sst.cases {
        let l = match &case.label {
            hir::CaseLabel::Case(e) => Some(ex_to(state, e, &head_ty, false)),
            hir::CaseLabel::Def => None,
        };
        pending.push(l);
        if !case.stmts.is_empty() {
            groups.push((mem::take(&mut pending), &case.stmts));
        }
    }
    if !pending.is_empty() {
        groups.push((pending, &[]));
    }
    for (i, (_, stmts)) in groups.iter().enumerate() {
        if i + 1 < groups.len() && falls_through(stmts) {
            panic!("switch case falling through into the next case is not supported");
        }
    }

    let mut default: Option<&[Statement]> = None;
    let mut first = true;
    state.breaks.borrow_mut().push(Brk::Switch(label));
    for (labels, stmts) in &groups {
        if labels.iter().any(|l| l.is_none()) {
            default = Some(stmts);
            continue;
        }
        let cond: Vec<String> = labels.iter().map(|l| format!("_sw{}_ == {}", label, l.as_ref().unwrap())).collect();
        show_indent(state);
        writeln!(state, "{}if {} {{", if first { "" } else { "} else " }, cond.join(" || "));
        first = false;
        state.indent();
        show_case_body(state, stmts);
        state.outdent();
    }
    if let Some(stmts) = default {
        if first {
            show_indent(state);
            state.write("{\n");
        } else {
            show_indent(state);
            state.write("} else {\n");
        }
        state.indent();
        show_case_body(state, stmts);
        state.outdent();
        show_indent(state);
        state.write("}\n");
    } else if !first {
        show_indent(state);
        state.write("}\n");
    }
    state.breaks.borrow_mut().pop();
    state.outdent();
    show_indent(state);
    state.write("}\n");
}

/// A case body without its trailing `break`.
fn show_case_body(state: &mut OutputState, stmts: &[Statement]) {
    let stmts = match stmts.split_last() {
        Some((hir::Statement::Simple(s), rest))
            if matches!(**s, hir::SimpleStatement::Jump(hir::JumpStatement::Break)) =>
        {
            rest
        }
        _ => stmts,
    };
    for st in stmts {
        show_statement(state, st);
    }
}

/// Whether `continue` appears in `s` outside nested loops.
fn has_continue(s: &hir::Statement) -> bool {
    match s {
        hir::Statement::Compound(c) => c.statement_list.iter().any(has_continue),
        hir::Statement::Simple(s) => match &**s {
            hir::SimpleStatement::Jump(hir::JumpStatement::Continue) => true,
            hir::SimpleStatement::Selection(sel) => {
                has_continue(&sel.body) || sel.else_stmt.as_ref().is_some_and(|e| has_continue(e))
            }
            hir::SimpleStatement::Switch(sw) => sw.cases.iter().any(|c| c.stmts.iter().any(has_continue)),
            _ => false,
        },
    }
}

fn new_label(state: &OutputState) -> usize {
    let label = state.label_index.get();
    state.label_index.set(label + 1);
    label
}

/// The body of loop `'l<label>`: `break` and `continue` inside it name the loop (Rust refuses unlabeled ones
/// inside the labeled blocks a lowered `switch` or a do-while body is).
fn show_loop_body(state: &mut OutputState, body: &hir::Statement, label: usize, is_do: bool) {
    state.breaks.borrow_mut().push(Brk::Loop(label, is_do));
    show_statement(state, body);
    state.breaks.borrow_mut().pop();
}

fn show_iteration_statement(state: &mut OutputState, ist: &hir::IterationStatement) {
    show_indent(state);
    match *ist {
        hir::IterationStatement::While(ref cond, ref body) => {
            let label = new_label(state);
            let c = show_condition(state, cond);
            writeln!(state, "'l{}: while {} {{", label, c);
            state.indent();
            show_loop_body(state, body, label, false);
            state.outdent();
            show_indent(state);
            state.write("}\n");
        }
        hir::IterationStatement::DoWhile(ref body, ref cond) => {
            // `continue` must still test the condition: the body is a block it breaks out of (`break 'do<N>`).
            let label = new_label(state);
            writeln!(state, "'l{}: loop {{", label);
            state.indent();
            show_indent(state);
            writeln!(state, "'do{}: {{", label);
            state.indent();
            show_loop_body(state, body, label, true);
            state.outdent();
            show_indent(state);
            state.write("}\n");
            show_indent(state);
            let c = ex_to(state, cond, &Type::new(TypeKind::Bool), false);
            writeln!(state, "if !({}) {{", c);
            show_indent(state);
            writeln!(state, "    break 'l{};", label);
            show_indent(state);
            state.write("}\n");
            state.outdent();
            show_indent(state);
            state.write("}\n");
        }
        hir::IterationStatement::For(ref init, ref rest, ref body) => {
            state.write("{\n");
            state.indent();
            match init {
                hir::ForInitStatement::Expression(Some(e)) => {
                    show_indent(state);
                    let code = ex_inner(state, e, true);
                    writeln!(state, "{};", code);
                }
                hir::ForInitStatement::Expression(None) => {}
                hir::ForInitStatement::Declaration(d) => show_declaration(state, d),
            }
            let label = new_label(state);
            let cond = match &rest.condition {
                Some(c) => show_condition(state, c),
                None => "true".to_string(),
            };
            let post = rest.post_expr.as_ref().map(|e| ex_inner(state, e, true));
            show_indent(state);
            if let (true, Some(post_code)) = (has_continue(body), post.as_ref()) {
                // `continue` must still run the post expression: it runs at the top of every iteration but the
                // first, inside the condition.
                let first = state.tmp("first");
                writeln!(state, "let mut {} = true;", first);
                show_indent(state);
                writeln!(
                    state,
                    "'l{3}: while {{ if !{0} {{ {1}; }} {0} = false; {2} }} {{",
                    first, post_code, cond, label
                );
                state.indent();
                show_loop_body(state, body, label, false);
                state.outdent();
            } else {
                writeln!(state, "'l{}: while {} {{", label, cond);
                state.indent();
                show_loop_body(state, body, label, false);
                if let Some(p) = &post {
                    show_indent(state);
                    writeln!(state, "{};", p);
                }
                state.outdent();
            }
            show_indent(state);
            state.write("}\n");
            state.outdent();
            show_indent(state);
            state.write("}\n");
        }
    }
}

fn show_condition(state: &mut OutputState, c: &hir::Condition) -> String {
    match *c {
        hir::Condition::Expr(ref e) => ex_to(state, e, &Type::new(TypeKind::Bool), false),
    }
}

fn use_return_mask(state: &OutputState) -> bool {
    if let Some(mask) = &state.mask {
        mask.kind != hir::ExprKind::CondMask
    } else {
        false
    }
}

/// `I32(mask)` in the C++: the mask as lanes (or as `i32` in a scalar function).
fn ret_mask_cast(state: &OutputState, mask: &hir::Expr) -> String {
    if state.return_vector {
        mask_lanes(state, mask)
    } else {
        format!("({} as i32)", paren(ex(state, mask)))
    }
}

fn show_jump_statement(state: &mut OutputState, j: &hir::JumpStatement) {
    show_indent(state);
    match *j {
        hir::JumpStatement::Continue => {
            let target = state.breaks.borrow().iter().rev().find_map(|b| match b {
                Brk::Loop(l, is_do) => Some((*l, *is_do)),
                _ => None,
            });
            match target {
                Some((l, true)) => {
                    writeln!(state, "break 'do{};", l);
                }
                Some((l, false)) => {
                    writeln!(state, "continue 'l{};", l);
                }
                None => panic!("continue outside a loop"),
            }
        }
        hir::JumpStatement::Break => {
            let target = state.breaks.borrow().last().copied();
            match target {
                Some(Brk::Body) => state.write("break 'body;\n"),
                Some(Brk::Switch(l)) => {
                    writeln!(state, "break 'sw{};", l);
                }
                Some(Brk::Loop(l, _)) => {
                    writeln!(state, "break 'l{};", l);
                }
                None => panic!("break outside a loop or switch"),
            }
        }
        hir::JumpStatement::Discard => {
            state.uses_discard = true;
            if let Some(mask) = &state.mask {
                let mut m = mask_lanes(state, mask);
                if state.return_declared {
                    m = format!("({}) & ret_mask", m);
                }
                writeln!(state, "self.fs.swgl_IsPixelDiscarded = self.fs.swgl_IsPixelDiscarded | ({});", m);
            } else {
                writeln!(state, "self.fs.swgl_IsPixelDiscarded = {}::from(1i32);", state.rt("glsl", "Bool"));
            }
        }
        hir::JumpStatement::Return(ref e) => {
            let ret_ty = state.return_type.clone().map(|t| *t).unwrap_or(Type::new(TypeKind::Void));
            if let Some(e) = e {
                if use_return_mask(state) {
                    let mask = state.mask.clone().unwrap();
                    if state.return_declared {
                        let value = ex_to(state, e, &ret_ty, state.return_vector);
                        let m = ret_mask_cast(state, &mask);
                        let ite = state.rt("glsl", "if_then_else");
                        writeln!(state, "ret = {}(ret_mask & {}, {}, ret);", ite, m, value);
                    } else {
                        let value = ex_to(state, e, &ret_ty, state.return_vector);
                        writeln!(state, "ret = {};", value);
                    }

                    show_indent(state);

                    let m = ret_mask_cast(state, &mask);
                    if state.return_declared {
                        writeln!(state, "ret_mask = ret_mask & !({});", m);
                    } else {
                        writeln!(state, "ret_mask = !({});", m);
                    }
                    state.return_declared = true;
                } else if state.return_declared {
                    let value = ex_to(state, e, &ret_ty, state.return_vector);
                    let ite = state.rt("glsl", "if_then_else");
                    writeln!(state, "ret = {}(ret_mask, {}, ret);", ite, value);
                } else {
                    let value = ex_to(state, e, &ret_ty, state.return_vector);
                    writeln!(state, "return {};", value);
                }
            } else if use_return_mask(state) {
                let mask = state.mask.clone().unwrap();
                let m = ret_mask_cast(state, &mask);
                if state.return_declared {
                    writeln!(state, "ret_mask = ret_mask & !({});", m);
                } else {
                    writeln!(state, "ret_mask = !({});", m);
                }
                state.return_declared = true;
            } else {
                state.write("return;\n");
            }
        }
    }
}

/// Writes variant `vector_mask` of user function `name` and, before it, the variants it calls.
fn show_function_variant(state: &mut OutputState, name: hir::SymRef, vector_mask: u32) {
    if let Some((ref fd, run_class)) = state.hir.function_definition(name) {
        state.vector_mask = vector_mask;
        state.return_vector = (vector_mask & (1 << 31)) != 0
            || match run_class {
                hir::RunClass::Scalar => false,
                hir::RunClass::Dependent(mask) => (mask & vector_mask) != 0,
                _ => true,
            };
        match state.functions.get(&(name, vector_mask)) {
            Some(_) => {}
            None => {
                state.functions.insert((name, vector_mask), false);
                let buffer = state.push_buffer();
                show_function_definition(state, fd, name, vector_mask);
                for (name, vector_mask) in state.deps.replace(Vec::new()) {
                    show_function_variant(state, name, vector_mask);
                }
                state.flush_buffer();
                state.pop_buffer(buffer);
                state.functions.insert((name, vector_mask), true);
            }
        }
    }
}

// ---- the stage structs and the ABI --------------------------------------------------------------------------------

fn sampler_kind(tk: &hir::TypeKind) -> bool {
    matches!(tk, hir::TypeKind::Sampler2D | hir::TypeKind::Sampler2DRect | hir::TypeKind::ISampler2D)
}

/// The `<name>_common` struct: samplers, attribute locations, flat varyings, uniforms (C++ `write_common_globals`).
fn write_common_globals(
    state: &mut OutputState,
    attribs: &[hir::SymRef],
    outputs: &[hir::SymRef],
    uniforms: &UniformIndices,
) {
    // struct Samplers
    state.write("#[derive(Clone, Default)]\npub struct Samplers {\n");
    for (name, (_, tk, storage)) in uniforms.iter() {
        if sampler_kind(tk) {
            let suffix = if let hir::StorageClass::Sampler(format) = storage { format.type_suffix() } else { None };
            let impl_ty = format!("{}{}_impl", tk.glsl_primitive_type_name().unwrap(), suffix.unwrap_or(""));
            writeln!(state, "    pub {}_impl: {},", name, state.rt("glsl", &impl_ty));
            writeln!(state, "    pub {}_slot: i32,", name);
        }
    }
    state.write("}\n\nimpl Samplers {\n    pub fn set_slot(&mut self, index: i32, value: i32) -> bool {\n");
    state.write("        match index {\n");
    for (name, (index, tk, _)) in uniforms.iter() {
        if sampler_kind(tk) {
            write!(state, "            {} => {{\n                self.{}_slot = value;\n", index, name);
            state.write("                true\n            }\n");
        }
    }
    state.write("            _ => false,\n        }\n    }\n}\n\n");

    // struct AttribLocations
    state.write("#[derive(Clone)]\npub struct AttribLocations {\n");
    for i in attribs {
        let sym = state.hir.sym(*i);
        writeln!(state, "    pub {}: i32,", sym.name);
    }
    state.write("}\n\nimpl Default for AttribLocations {\n    fn default() -> Self {\n        AttribLocations {");
    for (n, i) in attribs.iter().enumerate() {
        let sym = state.hir.sym(*i);
        write!(state, "{} {}: {} as i32", if n > 0 { "," } else { "" }, sym.name, state.rt("program", "NULL_ATTRIB"));
    }
    state.write(" }\n    }\n}\n\nimpl AttribLocations {\n");
    state.write("    pub fn bind_loc(&mut self, name: &str, index: i32) {\n        match name {\n");
    for i in attribs {
        let sym = state.hir.sym(*i);
        writeln!(state, "            \"{0}\" => self.{0} = index,", sym.name);
    }
    state.write("            _ => {}\n        }\n    }\n\n");
    state.write("    pub fn get_loc(&self, name: &str) -> i32 {\n        match name {\n");
    for i in attribs {
        let sym = state.hir.sym(*i);
        write!(
            state,
            "            \"{0}\" => {{\n                if self.{0} != NULL_ATTRIB as i32 {{\n                    self.{0}\n                }} else {{\n                    -1\n                }}\n            }}\n",
            sym.name
        );
    }
    state.write("            _ => -1,\n        }\n    }\n}\n\n");

    write!(state, "#[derive(Clone, Default)]\npub struct {}_common {{\n", state.name);
    state.write("    pub samplers: Samplers,\n    pub attrib_locations: AttribLocations,\n");
    for i in outputs {
        let sym = state.hir.sym(*i);
        if let hir::SymDecl::Global(hir::StorageClass::Out, _, ty, hir::RunClass::Scalar) = &sym.decl {
            let t = type_name(state, ty, true);
            writeln!(state, "    pub {}: {},", sym.name, t);
        }
    }
    for (name, (_, tk, storage)) in uniforms {
        match storage {
            hir::StorageClass::Sampler(format) => {
                let t = format!("{}{}", tk.glsl_primitive_type_name().unwrap(), format.type_suffix().unwrap_or(""));
                writeln!(state, "    pub {}: {},", name, state.rt("glsl", &t));
            }
            _ => {
                let t = kind_name(state, tk, true);
                writeln!(state, "    pub {}: {},", name, t);
            }
        }
    }
    state.write("}\n\n");

    // bind_textures
    writeln!(state, "impl {}_common {{", state.name);
    state.write("    pub fn bind_textures(&mut self, ctx: &mut RasterState) {\n");
    for (name, (_, tk, storage)) in uniforms {
        if let hir::StorageClass::Sampler(_format) = storage {
            let f = match tk {
                hir::TypeKind::Sampler2D | hir::TypeKind::Sampler2DRect => "lookup_sampler",
                hir::TypeKind::ISampler2D => "lookup_isampler",
                _ => continue,
            };
            writeln!(
                state,
                "        self.{0} = {1}(ctx, &mut self.samplers.{0}_impl, self.samplers.{0}_slot);",
                name,
                state.rt("texture", f)
            );
        }
    }
    state.write("    }\n}\n\n");
}

/// The stage struct (`<name>_vert` holding the common struct, `<name>_frag` holding the vertex struct, as the
/// C++ inherits them) with `Deref` to what it holds, and its fields.
fn write_stage_struct(state: &mut OutputState, inputs: &[hir::SymRef], _outputs: &[hir::SymRef]) {
    let (inner, inner_ty, base, base_ty) = match state.kind {
        ShaderKind::Vertex => {
            ("common", format!("{}_common", state.name), "vs", state.rt("program", "VertexShaderState"))
        }
        ShaderKind::Fragment => {
            ("vert", format!("{}_vert", state.name), "fs", state.rt("program", "FragmentShaderState"))
        }
    };
    write!(state, "#[derive(Clone, Default)]\npub struct {} {{\n", state.part_name);
    writeln!(state, "    pub {}: {},", inner, inner_ty);
    writeln!(state, "    pub {}: {},", base, base_ty);
    for (n, t) in state.fields.borrow().iter() {
        writeln!(state, "    pub {}: {},", n, t);
    }
    if state.kind == ShaderKind::Fragment {
        state.write("    pub interp_step: InterpInputs,\n");
        let has_varying = inputs.iter().any(
            |i| matches!(&state.hir.sym(*i).decl, hir::SymDecl::Global(_, _, _, rc) if *rc != hir::RunClass::Scalar),
        );
        if has_varying {
            state.write("    pub interp_perspective: InterpPerspective,\n");
        }
    }
    state.write("}\n\n");
    write!(
        state,
        "impl Deref for {0} {{\n    type Target = {1};\n    #[inline(always)]\n    fn deref(&self) -> &{1} {{\n        &self.{2}\n    }}\n}}\n\n\
         impl DerefMut for {0} {{\n    #[inline(always)]\n    fn deref_mut(&mut self) -> &mut {1} {{\n        &mut self.{2}\n    }}\n}}\n\n",
        state.part_name, inner_ty, inner
    );
}

/// The vertex shader's interpolant outputs: `InterpOutputs` and `store_interp_outputs`.
fn write_store_outputs(state: &mut OutputState, outputs: &[hir::SymRef]) {
    // InterpOutputs is a module item; written into the struct list so it lands before the impls.
    let mut s = String::from("#[repr(C)]\n#[derive(Clone, Copy, Default)]\npub struct InterpOutputs {\n");
    if state.hir.used_clip_dist != 0 {
        let _ = writeln!(s, "    pub swgl_ClipDistance: {},", state.rt("glsl", "Float"));
    }
    let mut fields = Vec::new();
    // The field types, for the size the `Pod` assertion checks.
    let mut types = Vec::new();
    if state.hir.used_clip_dist != 0 {
        types.push(state.rt("glsl", "Float"));
    }
    for i in outputs {
        let sym = state.hir.sym(*i);
        if let hir::SymDecl::Global(_, _, ty, run_class) = &sym.decl {
            if *run_class != hir::RunClass::Scalar {
                let t = type_name(state, ty, true);
                let _ = writeln!(s, "    pub {}: {},", sym.name, t);
                fields.push(sym.name.clone());
                types.push(t);
            }
        }
    }
    let sizes: Vec<String> = types.iter().map(|t| format!("core::mem::size_of::<{t}>()")).collect();
    let sizes = if sizes.is_empty() { "0".to_string() } else { sizes.join(" + ") };
    // The 16-byte aligned clip distances leave tail padding after 4-byte varyings; a zeroed field fills it, so every
    // byte `store_interp` writes into the interpolant buffer (which the rasterizer reads as floats) is initialized.
    let pad_len = if state.hir.used_clip_dist != 0 {
        let float = state.rt("glsl", "Float");
        format!("(core::mem::align_of::<{float}>() - INTERP_FIELDS_SIZE % core::mem::align_of::<{float}>()) % core::mem::align_of::<{float}>() / 4")
    } else {
        "0".to_string()
    };
    if state.hir.used_clip_dist != 0 {
        s.push_str("    pub _pad: [f32; INTERP_PAD_LEN],\n");
    }
    s.push_str("}\n\n");
    let _ = writeln!(s, "const INTERP_FIELDS_SIZE: usize = {sizes};");
    let _ = writeln!(s, "const INTERP_PAD_LEN: usize = {pad_len};\n");
    let pod = state.rt("program", "Pod");
    let _ = writeln!(
        s,
        "// SAFETY: `InterpOutputs` is `repr(C)`, every field is `Pod`, and the fields fill it with no padding (asserted).\n\
         unsafe impl {pod} for InterpOutputs {{}}\n\
         const _: () = assert!(core::mem::size_of::<InterpOutputs>() == INTERP_FIELDS_SIZE + 4 * INTERP_PAD_LEN);\n"
    );
    s.push_str("pub type InterpInputs = InterpOutputs;\n\n");
    state.structs.borrow_mut().push(("InterpOutputs".into(), s));

    state.write("    #[inline(always)]\n    fn store_interp_outputs(&self, dest: &mut [u8], stride: usize) {\n");
    state.write("        for n in 0..4 {\n");
    state.write("            let mut out = InterpOutputs::default();\n");
    if state.hir.used_clip_dist != 0 {
        for i in 0..4 {
            if (state.hir.used_clip_dist & (1 << i)) != 0 {
                writeln!(
                    state,
                    "            out.swgl_ClipDistance[{0}] = {1}(self.vs.gl_ClipDistance[{0}], n);",
                    i,
                    state.rt("glsl", "get_nth")
                );
            } else {
                writeln!(state, "            out.swgl_ClipDistance[{}] = 0.0f32;", i);
            }
        }
    }
    for f in &fields {
        writeln!(state, "            out.{0} = {1}(self.{0}, n);", f, state.rt("glsl", "get_nth"));
    }
    writeln!(state, "            {}(&mut dest[n * stride..], &out);", state.rt("program", "store_interp"));
    state.write("        }\n    }\n");
}

/// The fragment shader's interpolant inputs: `read_interp_inputs`, `read_perspective_inputs`,
/// `step_interp_inputs`, `step_perspective_inputs` (C++ `write_read_inputs`).
fn write_read_inputs(state: &mut OutputState, inputs: &[hir::SymRef]) {
    let mut varyings = Vec::new();
    for i in inputs {
        let sym = state.hir.sym(*i);
        if let hir::SymDecl::Global(_, _, ty, run_class) = &sym.decl {
            if *run_class != hir::RunClass::Scalar {
                varyings.push((sym.name.clone(), type_name(state, ty, false)));
            }
        }
    }
    let has_varying = !varyings.is_empty();
    if has_varying {
        let mut s = String::from("#[derive(Clone, Copy, Default)]\npub struct InterpPerspective {\n");
        for (n, t) in &varyings {
            let _ = writeln!(s, "    pub {}: {},", n, t);
        }
        s.push_str("}\n\n");
        state.structs.borrow_mut().push(("InterpPerspective".into(), s));
    }
    let load = state.rt("program", "load_interp");
    let init_interp = state.rt("glsl", "init_interp");

    state.write("    fn read_interp_inputs(&mut self, init_: &[u8], step_: &[u8]) {\n");
    writeln!(state, "        let init: InterpInputs = {}(init_);", load);
    writeln!(state, "        let step: InterpInputs = {}(step_);", load);
    for (n, _) in &varyings {
        writeln!(state, "        self.{0} = {1}(init.{0}, step.{0});", n, init_interp);
        writeln!(state, "        self.interp_step.{0} = step.{0} * 4.0f32;", n);
    }
    state.write("    }\n\n");

    let used_fragcoord = state.used_fragcoord.get();
    if has_varying || (used_fragcoord & (4 | 8)) != 0 {
        state.use_perspective = true;
    }
    let float = state.rt("glsl", "Float");
    if state.use_perspective {
        state.write("    fn read_perspective_inputs(&mut self, init_: &[u8], step_: &[u8]) {\n");
        writeln!(state, "        let init: InterpInputs = {}(init_);", load);
        writeln!(state, "        let step: InterpInputs = {}(step_);", load);
        if has_varying {
            writeln!(state, "        let w: {0} = {0}::from(1.0f32) / self.fs.gl_FragCoord.w;", float);
        }
        for (n, t) in &varyings {
            writeln!(state, "        self.interp_perspective.{0} = {1}(init.{0}, step.{0});", n, init_interp);
            writeln!(state, "        self.{0} = self.interp_perspective.{0} * w;", n);
            writeln!(state, "        self.interp_step.{0} = step.{0} * 4.0f32;", n);
            state.require(format!("impl Mul<Float> for {}", t));
        }
        state.write("    }\n\n");
    }

    state.write("    #[inline(always)]\n    fn step_interp_inputs(&mut self, steps: i32) {\n");
    if (used_fragcoord & 1) != 0 {
        state.write("        self.fs.step_fragcoord(steps);\n");
    }
    if !inputs.is_empty() {
        state.write("        let chunks: f32 = steps as f32 * 0.25f32;\n");
    }
    for (n, t) in &varyings {
        writeln!(state, "        self.{0} = self.{0} + {1}::from(self.interp_step.{0} * chunks);", n, t);
    }
    state.write("    }\n");

    if state.use_perspective {
        state.write("\n    #[inline(always)]\n    fn step_perspective_inputs(&mut self, steps: i32) {\n");
        if (used_fragcoord & 1) != 0 {
            state.write("        self.fs.step_fragcoord(steps);\n");
        }
        state.write("        self.fs.step_perspective(steps);\n");
        if !inputs.is_empty() {
            state.write("        let chunks: f32 = steps as f32 * 0.25f32;\n");
        }
        if has_varying {
            writeln!(state, "        let w: {0} = {0}::from(1.0f32) / self.fs.gl_FragCoord.w;", float);
        }
        for (n, t) in &varyings {
            writeln!(
                state,
                "        self.interp_perspective.{0} = self.interp_perspective.{0} + {1}::from(self.interp_step.{0} * chunks);",
                n, t
            );
            writeln!(state, "        self.{0} = w * self.interp_perspective.{0};", n);
            state.require(format!("impl Mul<{}> for Float", t));
        }
        state.write("    }\n");
    }
}

/// The trait impls (C++: the static functions and the function pointer table filled in the constructor).
fn write_abi(state: &mut OutputState) {
    let name = state.part_name.clone();
    let ctx_main = state.hir.lookup("main").is_some_and(|s| state.info(s).needs_ctx);
    let main_call = if ctx_main { "self.main(ctx)" } else { "self.main()" };
    match state.kind {
        ShaderKind::Vertex => {
            let vsi = state.rt("program", "VertexShaderImpl");
            let attrib = state.rt("program", "VertexAttrib");
            write!(state, "impl {} {{\n    pub fn new() -> Self {{\n        let mut s = Self::default();\n", name);
            if state.hir.used_clip_dist != 0 {
                state.write("        s.vs.enable_clip_distance();\n");
            }
            state.write("        s\n    }\n}\n\n");

            writeln!(state, "impl {} for {} {{", vsi, name);
            let vss = state.rt("program", "VertexShaderState");
            write!(
                state,
                "    fn state(&self) -> &{0} {{\n        &self.vs\n    }}\n\n    fn state_mut(&mut self) -> &mut {0} {{\n        &mut self.vs\n    }}\n\n",
                vss
            );
            write_set_uniform(state, "set_uniform_1i", "value: i32");
            write_set_uniform(state, "set_uniform_4fv", "value: &[f32]");
            write_set_uniform(state, "set_uniform_matrix4fv", "value: &[f32]");
            state.write(
                "    fn init_batch(&mut self, ctx: &mut RasterState) {\n        self.bind_textures(ctx);\n    }\n\n",
            );
            write_load_attribs(state, &attrib);
            write!(
                state,
                "    fn run_primitive(&mut self, ctx: &mut RasterState, interps: &mut [u8], interp_stride: usize) {{\n        {};\n        self.store_interp_outputs(interps, interp_stride);\n    }}\n\n",
                main_call
            );
            write!(
                state,
                "    fn box_clone(&self) -> Box<dyn {}> {{\n        Box::new(self.clone())\n    }}\n}}\n\n",
                vsi
            );
        }
        ShaderKind::Fragment => {
            let fsi = state.rt("program", "FragmentShaderImpl");
            let fss = state.rt("program", "FragmentShaderState");
            write!(
                state,
                "impl {} {{\n    pub fn new() -> Self {{\n        let mut s = Self {{ vert: {}_vert::new(), ..Self::default() }};\n",
                name, state.name
            );
            if state.uses_discard {
                state.write("        s.fs.enable_discard();\n");
            }
            if state.use_perspective {
                state.write("        s.fs.enable_perspective();\n");
            }
            state.write("        s\n    }\n");
            for (fmt, f) in [("RGBA8", "swgl_drawSpanRGBA8"), ("R8", "swgl_drawSpanR8")] {
                if let Some(sym) = state.hir.lookup(f) {
                    let call =
                        if state.info(sym).needs_ctx { format!("self.{}(ctx)", f) } else { format!("self.{}()", f) };
                    write!(
                        state,
                        "\n    /// C++ `DISPATCH_DRAW_SPAN(self, {0})`.\n    fn draw_span_{0}(&mut self, ctx: &mut RasterState) -> i32 {{\n        let total = self.fs.swgl_SpanLength;\n        {1};\n        let drawn = total - self.fs.swgl_SpanLength;\n        if drawn != 0 {{\n            self.step_interp_inputs(drawn);\n        }}\n        drawn\n    }}\n",
                        fmt, call
                    );
                }
            }
            state.write("}\n\n");

            writeln!(state, "impl {} for {} {{", fsi, name);
            write!(
                state,
                "    fn state(&self) -> &{0} {{\n        &self.fs\n    }}\n\n    fn state_mut(&mut self) -> &mut {0} {{\n        &mut self.fs\n    }}\n\n",
                fss
            );
            let discard =
                if state.uses_discard { "        self.fs.swgl_IsPixelDiscarded = Bool::from(0i32);\n" } else { "" };
            if state.uses_discard {
                state.rt("glsl", "Bool");
            }
            state.write("    fn init_span_func(&mut self, interps: &[u8], step: &[u8]) {\n        self.read_interp_inputs(interps, step);\n    }\n\n");
            write!(
                state,
                "    fn run_func(&mut self, ctx: &mut RasterState) {{\n{}        {};\n        self.step_interp_inputs(4);\n    }}\n\n",
                discard, main_call
            );
            state
                .write("    fn skip_func(&mut self, steps: i32) {\n        self.step_interp_inputs(steps);\n    }\n\n");
            if state.use_perspective {
                state.write("    fn init_span_w_func(&mut self, interps: &[u8], step: &[u8]) {\n        self.read_perspective_inputs(interps, step);\n    }\n\n");
                write!(
                    state,
                    "    fn run_w_func(&mut self, ctx: &mut RasterState) {{\n{}        {};\n        self.step_perspective_inputs(4);\n    }}\n\n",
                    discard, main_call
                );
                state.write("    fn skip_w_func(&mut self, steps: i32) {\n        self.step_perspective_inputs(steps);\n    }\n\n");
            } else {
                state.write("    fn init_span_w_func(&mut self, interps: &[u8], step: &[u8]) {\n        self.read_interp_inputs(interps, step);\n    }\n\n");
                write!(
                    state,
                    "    fn run_w_func(&mut self, ctx: &mut RasterState) {{\n{}        {};\n        self.step_interp_inputs(4);\n    }}\n\n",
                    discard, main_call
                );
                state.write(
                    "    fn skip_w_func(&mut self, steps: i32) {\n        self.step_interp_inputs(steps);\n    }\n\n",
                );
            }
            for (fmt, lower, f) in [("RGBA8", "rgba8", "swgl_drawSpanRGBA8"), ("R8", "r8", "swgl_drawSpanR8")] {
                if state.hir.lookup(f).is_some() {
                    write!(
                        state,
                        "    fn draw_span_{0}_func(&mut self, ctx: &mut RasterState) -> i32 {{\n        self.draw_span_{1}(ctx)\n    }}\n\n    fn has_draw_span_{0}(&self) -> bool {{\n        true\n    }}\n\n",
                        lower, fmt
                    );
                } else {
                    write!(
                        state,
                        "    /// No `{1}` in this shader: the rasterizer checks `has_draw_span_{0}` first and never calls this.\n    fn draw_span_{0}_func(&mut self, _ctx: &mut RasterState) -> i32 {{\n        0\n    }}\n\n    fn has_draw_span_{0}(&self) -> bool {{\n        false\n    }}\n\n",
                        lower, f
                    );
                }
            }
            write!(
                state,
                "    fn box_clone(&self) -> Box<dyn {}> {{\n        Box::new(self.clone())\n    }}\n}}\n\n",
                fsi
            );
        }
    }
}

/// `set_uniform_1i`, `set_uniform_4fv`, `set_uniform_matrix4fv`: a `match` on the uniform index. The C++
/// `assert(0)` for a uniform of another type is `debug_assert!` (compiled out in release, as in swgl).
fn write_set_uniform(state: &mut OutputState, f: &str, param: &str) {
    let uniforms = state.uniform_list.clone();
    writeln!(state, "    fn {}(&mut self, index: i32, {}) {{", f, param);
    if f == "set_uniform_1i" {
        state.write("        if self.samplers.set_slot(index, value) {\n            return;\n        }\n");
    }
    state.write("        match index {\n");
    for (name, index, tk) in uniforms {
        let assign = match (f, tk) {
            ("set_uniform_1i", hir::TypeKind::Int) => Some(format!("self.{} = value", name)),
            ("set_uniform_4fv", hir::TypeKind::Vec4) => {
                Some(format!("self.{} = {}::load_from_ptr(value)", name, state.rt("glsl", "vec4_scalar")))
            }
            ("set_uniform_matrix4fv", hir::TypeKind::Mat4) => {
                Some(format!("self.{} = {}::load_from_ptr(value)", name, state.rt("glsl", "mat4_scalar")))
            }
            _ => None,
        };
        match assign {
            Some(a) => {
                writeln!(state, "            {} => {},", index, a);
            }
            None => {
                writeln!(state, "            {} => debug_assert!(false, \"{}\"),", index, name);
            }
        }
    }
    state.write("            _ => {}\n        }\n    }\n\n");
}

fn write_load_attribs(state: &mut OutputState, attrib: &str) {
    writeln!(
        state,
        "    fn load_attribs(&mut self, attribs: &[{}<'_>], start: u32, instance: i32, count: i32) {{",
        attrib
    );
    for (name, flat) in state.attribs.clone() {
        let f = if flat { state.rt("program", "load_flat_attrib") } else { state.rt("program", "load_attrib") };
        write!(
            state,
            "        let loc = self.attrib_locations.{0} as usize;\n        {1}(&mut self.{0}, &attribs[loc], start, instance, count);\n",
            name, f
        );
    }
    state.write("    }\n\n");
}

/// The program struct and its `ProgramImpl` (C++ `<name>_program`), and `loader()`.
fn write_program(state: &mut OutputState, uniform_indices: &UniformIndices) {
    let name = state.name.clone();
    let pi = state.rt("program", "ProgramImpl");
    let vsi = state.rt("program", "VertexShaderImpl");
    let fsi = state.rt("program", "FragmentShaderImpl");
    write!(
        state,
        "#[derive(Clone)]\npub struct {0}_program {{\n    pub frag: {0}_frag,\n}}\n\n\
         impl Deref for {0}_program {{\n    type Target = {0}_frag;\n    #[inline(always)]\n    fn deref(&self) -> &{0}_frag {{\n        &self.frag\n    }}\n}}\n\n\
         impl DerefMut for {0}_program {{\n    #[inline(always)]\n    fn deref_mut(&mut self) -> &mut {0}_frag {{\n        &mut self.frag\n    }}\n}}\n\n\
         impl {0}_program {{\n    pub fn loader() -> Box<dyn {1}> {{\n        Box::new({0}_program {{ frag: {0}_frag::new() }})\n    }}\n}}\n\n",
        name, pi
    );
    writeln!(state, "impl {} for {}_program {{", pi, name);
    state.write("    fn get_uniform(&self, name: &str) -> i32 {\n        match name {\n");
    for (uniform_name, (index, _, _)) in uniform_indices.iter() {
        writeln!(state, "            \"{}\" => {},", uniform_name, index);
    }
    state.write("            _ => -1,\n        }\n    }\n\n");
    state.write("    fn bind_attrib(&mut self, name: &str, index: i32) {\n        self.attrib_locations.bind_loc(name, index);\n    }\n\n");
    state
        .write("    fn get_attrib(&self, name: &str) -> i32 {\n        self.attrib_locations.get_loc(name)\n    }\n\n");
    state.write("    fn interpolants_size(&self) -> usize {\n        core::mem::size_of::<InterpOutputs>()\n    }\n\n");
    write!(
        state,
        "    fn get_vertex_shader(&mut self) -> &mut dyn {} {{\n        &mut self.frag.vert\n    }}\n\n",
        vsi
    );
    write!(state, "    fn get_fragment_shader(&mut self) -> &mut dyn {} {{\n        &mut self.frag\n    }}\n\n", fsi);
    write!(state, "    fn get_name(&self) -> &str {{\n        \"{}\"\n    }}\n\n", name);
    write!(state, "    fn box_clone(&self) -> Box<dyn {}> {{\n        Box::new(self.clone())\n    }}\n}}\n", pi);
}
