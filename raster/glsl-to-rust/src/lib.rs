#[derive(PartialEq, Eq, Clone, Copy)]
enum ShaderKind {
    Fragment,
    Vertex,
}

type UniformIndices = BTreeMap<String, (i32, hir::TypeKind, hir::StorageClass)>;

fn build_uniform_indices(indices: &mut UniformIndices, state: &hir::State) {
    for u in state.used_globals.borrow().iter() {
        let sym = state.sym(*u);
        if let hir::SymDecl::Global(storage, _, ty, _) = &sym.decl {
            match storage {
                hir::StorageClass::Uniform | hir::StorageClass::Sampler(..) => {
                    let next_index = indices.len() as i32 + 1;
                    indices.entry(sym.name.clone()).or_insert((next_index, ty.kind, *storage));
                }
                _ => {}
            }
        }
    }
}

/// Runtime modules the emitted code imports from, in the order the `use` lines are written.
const MODULES: [&str; 4] = ["glsl", "texture", "ext", "program"];

/// What one stage (vertex or fragment) contributes to the program's module.
struct StageOutput {
    /// Struct definitions from the GLSL, by name, shared between the stages.
    structs: Vec<(String, String)>,
    /// The stage struct, its impls and (for the fragment stage) the program struct.
    body: String,
    runtime: BTreeSet<(&'static str, String)>,
    requires: BTreeSet<String>,
}

/// Translates one program: `args` are the command name, then the preprocessed `<name>.vert` and `<name>.frag`.
/// Returns the source of one Rust module (a file to load with `#[path = ...] mod <name>;` inside the runtime crate).
pub fn translate(args: &mut dyn Iterator<Item = String>) -> String {
    let _cmd_name = args.next();
    let vertex_file = args.next().unwrap();

    let vs_name = std::path::Path::new(&vertex_file).file_stem().unwrap().to_string_lossy().to_string();

    let frag_file = args.next().unwrap();

    let fs_name = std::path::Path::new(&frag_file).file_stem().unwrap().to_string_lossy().to_string();

    let (vs_state, vs_hir, vs_is_frag) = parse_shader(vertex_file);
    let (fs_state, fs_hir, fs_is_frag) = parse_shader(frag_file);

    // we use a BTree so that iteration is stable
    let mut uniform_indices = BTreeMap::new();
    build_uniform_indices(&mut uniform_indices, &vs_state);
    build_uniform_indices(&mut uniform_indices, &fs_state);

    assert_eq!(fs_name, vs_name);

    let vs = translate_shader(vs_name.clone(), vs_state, vs_hir, vs_is_frag, &uniform_indices);
    let fs = translate_shader(fs_name, fs_state, fs_hir, fs_is_frag, &uniform_indices);

    let mut runtime: BTreeSet<(&'static str, String)> = vs.runtime;
    runtime.extend(fs.runtime);
    let mut requires = vs.requires;
    requires.extend(fs.requires);

    let mut result = String::new();
    let _ = write!(
        result,
        "// Generated by glsl-to-rust from {0}.vert and {0}.frag (WebRender's GLSL, preprocessed as swgl does).\n\
         // Do not edit: change raster/glsl-to-rust instead. The C++ that glsl-to-cxx makes from the same files\n\
         // has the same structs, functions, locals and temporaries under the same names; a function with several\n\
         // vector variants (C++ overloads) has one method per variant, suffixed (raster/glsl-to-rust/README.md).\n\
         #![allow(non_camel_case_types, non_snake_case, non_upper_case_globals, unused_parens, unused_braces,\n    \
         unused_mut, unused_variables, unused_assignments, unused_imports, unused_unsafe, dead_code,\n    \
         unreachable_code, unreachable_patterns, unused_labels, clippy::all)]\n\n",
        vs_name
    );
    result.push_str("use core::ops::{Deref, DerefMut};\n");
    for module in MODULES {
        let names: Vec<&str> = runtime.iter().filter(|(m, _)| *m == module).map(|(_, n)| n.as_str()).collect();
        if names.is_empty() {
            continue;
        }
        let _ = write!(result, "use crate::{}::{{", module);
        let mut width = 20 + module.len();
        for (i, n) in names.iter().enumerate() {
            if i > 0 {
                result.push(',');
                width += 1;
                if width + n.len() > 110 {
                    result.push_str("\n    ");
                    width = 4;
                } else {
                    result.push(' ');
                    width += 1;
                }
            }
            result.push_str(n);
            width += n.len();
        }
        result.push_str("};\n");
    }
    result.push_str("use crate::RasterState;\n\n");

    // GLSL structs: both stages declare them from the same source; emit each once.
    let mut seen: HashMap<String, String> = HashMap::new();
    for (name, code) in vs.structs.iter().chain(fs.structs.iter()) {
        match seen.get(name) {
            Some(prev) if prev == code => {}
            Some(_) => panic!("struct {} differs between the vertex and the fragment shader", name),
            None => {
                seen.insert(name.clone(), code.clone());
                result.push_str(code);
            }
        }
    }

    result.push_str(&vs.body);
    result.push('\n');
    result.push_str(&fs.body);

    if !requires.is_empty() {
        result.push_str("\n// What this module needs from the runtime beyond the names imported above:\n");
        for r in &requires {
            let _ = writeln!(result, "// requires: {}", r);
        }
    }
    result
}

fn parse_shader(file: String) -> (hir::State, hir::TranslationUnit, bool) {
    let mut contents = String::new();
    let is_frag = file.contains("frag");
    std::fs::File::open(&file).unwrap().read_to_string(&mut contents).unwrap();
    let r = TranslationUnit::parse(contents);

    let r = match r {
        Ok(ok) => ok,
        Err(e) => panic!("failed to parse {:?}: {:?}", file, e),
    };

    let mut state = hir::State::new();
    let hir = hir::ast_to_hir(&mut state, &r);
    (state, hir, is_frag)
}

/// Per user function: whether it needs `ctx` (it or a callee touches swgl's raster statics) and whether it
/// mutates the shader object (`&mut self` rather than `&self`).
#[derive(Clone, Copy, Default, PartialEq)]
struct FnInfo {
    needs_ctx: bool,
    mut_self: bool,
}

/// The intrinsics that read or write the raster state swgl keeps in C++ statics (`blend_key`, `swgl_ClipFlags`,
/// `swgl_ClipMask*`, `swgl_AAEdgeMask`, `swgl_BlendOverride`, `swgl_BlendColorRGBA8`, ...): they take `ctx` first.
fn native_needs_ctx(name: &str) -> bool {
    name.starts_with("swgl_commit")
        || matches!(name, "swgl_clipMask" | "swgl_antiAlias" | "swgl_blendDropShadow" | "swgl_blendSubpixelText")
}

/// The span intrinsics that advance the span output (`swgl_OutRGBA8`/`swgl_OutR8`, `swgl_SpanLength`, and for the
/// dithered ones `gl_FragCoord`): they take `&mut self.fs` (the `FragmentShaderState`) last.
fn native_needs_fs(name: &str) -> bool {
    name.starts_with("swgl_commit")
}

/// Natives whose arguments keep their own run class (no lane promotion): the swgl intrinsics and texture access,
/// whose C++ overloads are specific (a scalar LOD, a scalar rect next to vector coordinates).
fn native_passthrough(name: &str) -> bool {
    name.starts_with("swgl_") || name.starts_with("texture") || name.starts_with("texel")
}

/// The runtime module a native function lives in.
fn native_module(name: &str) -> &'static str {
    if name.starts_with("swgl_") {
        "ext"
    } else if name.starts_with("texture") || name.starts_with("texel") || name.starts_with("lookup_") {
        "texture"
    } else {
        "glsl"
    }
}

fn collect_calls_expr(e: &hir::Expr, out: &mut Vec<SymRef>) {
    use hir::ExprKind::*;
    match &e.kind {
        Variable(_) | IntConst(_) | UIntConst(_) | BoolConst(_) | FloatConst(_) | DoubleConst(_) | CondMask => {}
        Unary(_, a) | Dot(a, _) | SwizzleSelector(a, _) | PostInc(a) | PostDec(a) | Cond(_, a) => {
            collect_calls_expr(a, out)
        }
        Binary(_, a, b) | Assignment(a, _, b) | Comma(a, b) => {
            collect_calls_expr(a, out);
            collect_calls_expr(b, out);
        }
        Ternary(a, b, c) => {
            collect_calls_expr(a, out);
            collect_calls_expr(b, out);
            collect_calls_expr(c, out);
        }
        Bracket(a, idx) => {
            collect_calls_expr(a, out);
            for i in idx {
                collect_calls_expr(i, out);
            }
        }
        FunCall(f, args) => {
            if let hir::FunIdentifier::Identifier(s) = f {
                out.push(*s);
            }
            for a in args {
                collect_calls_expr(a, out);
            }
        }
    }
}

fn collect_calls_init(i: &hir::Initializer, out: &mut Vec<SymRef>) {
    match i {
        hir::Initializer::Simple(e) => collect_calls_expr(e, out),
        hir::Initializer::List(l) => {
            for i in &l.0 {
                collect_calls_init(i, out)
            }
        }
    }
}

fn collect_calls_decl(d: &hir::Declaration, out: &mut Vec<SymRef>) {
    if let hir::Declaration::InitDeclaratorList(l) = d {
        if let Some(i) = &l.head.initializer {
            collect_calls_init(i, out);
        }
        for t in &l.tail {
            if let Some(i) = &t.initializer {
                collect_calls_init(i, out);
            }
        }
    }
}

fn collect_calls_stmt(s: &hir::Statement, out: &mut Vec<SymRef>, discard: &mut bool) {
    match s {
        hir::Statement::Compound(c) => {
            for s in &c.statement_list {
                collect_calls_stmt(s, out, discard);
            }
        }
        hir::Statement::Simple(s) => match &**s {
            hir::SimpleStatement::Declaration(d) => collect_calls_decl(d, out),
            hir::SimpleStatement::Expression(e) => {
                if let Some(e) = e {
                    collect_calls_expr(e, out);
                }
            }
            hir::SimpleStatement::Selection(sel) => {
                collect_calls_expr(&sel.cond, out);
                collect_calls_stmt(&sel.body, out, discard);
                if let Some(e) = &sel.else_stmt {
                    collect_calls_stmt(e, out, discard);
                }
            }
            hir::SimpleStatement::Switch(sw) => {
                collect_calls_expr(&sw.head, out);
                for c in &sw.cases {
                    if let hir::CaseLabel::Case(e) = &c.label {
                        collect_calls_expr(e, out);
                    }
                    for s in &c.stmts {
                        collect_calls_stmt(s, out, discard);
                    }
                }
            }
            hir::SimpleStatement::Iteration(it) => match it {
                hir::IterationStatement::While(hir::Condition::Expr(c), b) => {
                    collect_calls_expr(c, out);
                    collect_calls_stmt(b, out, discard);
                }
                hir::IterationStatement::DoWhile(b, c) => {
                    collect_calls_stmt(b, out, discard);
                    collect_calls_expr(c, out);
                }
                hir::IterationStatement::For(init, rest, b) => {
                    match init {
                        hir::ForInitStatement::Expression(Some(e)) => collect_calls_expr(e, out),
                        hir::ForInitStatement::Expression(None) => {}
                        hir::ForInitStatement::Declaration(d) => collect_calls_decl(d, out),
                    }
                    if let Some(hir::Condition::Expr(c)) = &rest.condition {
                        collect_calls_expr(c, out);
                    }
                    if let Some(p) = &rest.post_expr {
                        collect_calls_expr(p, out);
                    }
                    collect_calls_stmt(b, out, discard);
                }
            },
            hir::SimpleStatement::Jump(j) => match j {
                hir::JumpStatement::Return(Some(e)) => collect_calls_expr(e, out),
                hir::JumpStatement::Discard => *discard = true,
                _ => {}
            },
        },
    }
}

/// Calls `f` on `e` and every expression inside it.
fn walk_expr(e: &hir::Expr, f: &mut dyn FnMut(&hir::Expr)) {
    use hir::ExprKind::*;
    f(e);
    match &e.kind {
        Variable(_) | IntConst(_) | UIntConst(_) | BoolConst(_) | FloatConst(_) | DoubleConst(_) | CondMask => {}
        Unary(_, a) | Dot(a, _) | SwizzleSelector(a, _) | PostInc(a) | PostDec(a) | Cond(_, a) => walk_expr(a, f),
        Binary(_, a, b) | Assignment(a, _, b) | Comma(a, b) => {
            walk_expr(a, f);
            walk_expr(b, f);
        }
        Ternary(a, b, c) => {
            walk_expr(a, f);
            walk_expr(b, f);
            walk_expr(c, f);
        }
        Bracket(a, idx) => {
            walk_expr(a, f);
            for i in idx {
                walk_expr(i, f);
            }
        }
        FunCall(_, args) => {
            for a in args {
                walk_expr(a, f);
            }
        }
    }
}

/// Whether evaluating `e` writes a global (a uniform-struct field, a varying, `gl_Position`, a fragment output):
/// the function then takes `&mut self`. The HIR's `FunctionDefinition::globals` misses fragment outputs.
fn writes_global(state: &hir::State, e: &hir::Expr) -> bool {
    let is_global = |e: &hir::Expr| match place_root(e) {
        Some((s, _)) => matches!(state.sym(s).decl, hir::SymDecl::Global(..)),
        None => false,
    };
    let mut writes = false;
    walk_expr(e, &mut |e| match &e.kind {
        hir::ExprKind::Assignment(l, ..) | hir::ExprKind::PostInc(l) | hir::ExprKind::PostDec(l) => {
            writes |= is_global(l)
        }
        hir::ExprKind::Unary(UnaryOp::Inc | UnaryOp::Dec, l) => writes |= is_global(l),
        hir::ExprKind::FunCall(hir::FunIdentifier::Identifier(f), args) => {
            if let hir::SymDecl::UserFunction(fd, _) = &state.sym(*f).decl {
                for (p, a) in fd.prototype.parameters.iter().zip(args) {
                    if let hir::FunctionParameterDeclaration::Named(
                        Some(hir::ParameterQualifier::Out | hir::ParameterQualifier::InOut),
                        _,
                    ) = p
                    {
                        writes |= is_global(a);
                    }
                }
            }
        }
        _ => {}
    });
    writes
}

/// Calls `f` on every top-level expression of a statement (conditions, initializers, expression statements).
fn walk_stmt_exprs(s: &hir::Statement, f: &mut dyn FnMut(&hir::Expr)) {
    fn init(i: &hir::Initializer, f: &mut dyn FnMut(&hir::Expr)) {
        match i {
            hir::Initializer::Simple(e) => f(e),
            hir::Initializer::List(l) => {
                for i in &l.0 {
                    init(i, f)
                }
            }
        }
    }
    fn decl(d: &hir::Declaration, f: &mut dyn FnMut(&hir::Expr)) {
        if let hir::Declaration::InitDeclaratorList(l) = d {
            if let Some(i) = &l.head.initializer {
                init(i, f);
            }
            for t in &l.tail {
                if let Some(i) = &t.initializer {
                    init(i, f);
                }
            }
        }
    }
    match s {
        hir::Statement::Compound(c) => {
            for s in &c.statement_list {
                walk_stmt_exprs(s, f);
            }
        }
        hir::Statement::Simple(s) => match &**s {
            hir::SimpleStatement::Declaration(d) => decl(d, f),
            hir::SimpleStatement::Expression(Some(e)) => f(e),
            hir::SimpleStatement::Expression(None) => {}
            hir::SimpleStatement::Selection(sel) => {
                f(&sel.cond);
                walk_stmt_exprs(&sel.body, f);
                if let Some(e) = &sel.else_stmt {
                    walk_stmt_exprs(e, f);
                }
            }
            hir::SimpleStatement::Switch(sw) => {
                f(&sw.head);
                for c in &sw.cases {
                    if let hir::CaseLabel::Case(e) = &c.label {
                        f(e);
                    }
                    for s in &c.stmts {
                        walk_stmt_exprs(s, f);
                    }
                }
            }
            hir::SimpleStatement::Iteration(it) => match it {
                hir::IterationStatement::While(hir::Condition::Expr(c), b) => {
                    f(c);
                    walk_stmt_exprs(b, f);
                }
                hir::IterationStatement::DoWhile(b, c) => {
                    walk_stmt_exprs(b, f);
                    f(c);
                }
                hir::IterationStatement::For(i, rest, b) => {
                    match i {
                        hir::ForInitStatement::Expression(Some(e)) => f(e),
                        hir::ForInitStatement::Expression(None) => {}
                        hir::ForInitStatement::Declaration(d) => decl(d, f),
                    }
                    if let Some(hir::Condition::Expr(c)) = &rest.condition {
                        f(c);
                    }
                    if let Some(p) = &rest.post_expr {
                        f(p);
                    }
                    walk_stmt_exprs(b, f);
                }
            },
            hir::SimpleStatement::Jump(hir::JumpStatement::Return(Some(e))) => f(e),
            hir::SimpleStatement::Jump(_) => {}
        },
    }
}

/// Computes [`FnInfo`] for every user function by a fixpoint over the call graph.
fn compute_fn_info(state: &hir::State, tu: &hir::TranslationUnit) -> HashMap<SymRef, FnInfo> {
    let mut calls: Vec<(SymRef, Vec<SymRef>, FnInfo)> = Vec::new();
    for ed in tu {
        if let hir::ExternalDeclaration::FunctionDefinition(fd) = ed {
            let sym = match state.lookup(fd.prototype.name.as_str()) {
                Some(s) => s,
                None => continue,
            };
            let mut out = Vec::new();
            let mut discard = false;
            for s in &fd.body.statement_list {
                collect_calls_stmt(s, &mut out, &mut discard);
            }
            let mut writes = false;
            for s in &fd.body.statement_list {
                walk_stmt_exprs(s, &mut |e| writes |= writes_global(state, e));
            }
            let mut info = FnInfo { needs_ctx: false, mut_self: !fd.globals.is_empty() || discard || writes };
            let mut user = Vec::new();
            for c in out {
                match &state.sym(c).decl {
                    hir::SymDecl::NativeFunction(..) => {
                        let name = state.sym(c).name.clone();
                        info.needs_ctx |= native_needs_ctx(&name);
                        info.mut_self |= native_needs_fs(&name) || name == "swgl_stepInterp";
                    }
                    hir::SymDecl::UserFunction(..) => user.push(c),
                    _ => {}
                }
            }
            calls.push((sym, user, info));
        }
    }
    let mut infos: HashMap<SymRef, FnInfo> = calls.iter().map(|(s, _, i)| (*s, *i)).collect();
    loop {
        let mut changed = false;
        for (s, callees, _) in &calls {
            let mut info = infos[s];
            for c in callees {
                if let Some(ci) = infos.get(c) {
                    info.needs_ctx |= ci.needs_ctx;
                    info.mut_self |= ci.mut_self;
                }
            }
            if info != infos[s] {
                infos.insert(*s, info);
                changed = true;
            }
        }
        if !changed {
            break;
        }
    }
    infos
}

/// Global `const` initializers, to evaluate array sizes and to choose between an associated `const` and an
/// associated function.
fn collect_const_inits(state: &hir::State, tu: &hir::TranslationUnit) -> HashMap<SymRef, hir::Initializer> {
    let mut m = HashMap::new();
    for ed in tu {
        if let hir::ExternalDeclaration::Declaration(hir::Declaration::InitDeclaratorList(d)) = ed {
            if let hir::SymDecl::Global(hir::StorageClass::Const, ..) = &state.sym(d.head.name).decl {
                if let Some(i) = &d.head.initializer {
                    m.insert(d.head.name, i.clone());
                }
            }
        }
    }
    m
}

fn translate_shader(
    name: String,
    mut state: hir::State,
    hir: hir::TranslationUnit,
    is_frag: bool,
    uniform_indices: &UniformIndices,
) -> StageOutput {
    hir::infer_run_class(&mut state, &hir);

    let mut inputs = Vec::new();
    let mut outputs = Vec::new();

    for i in &hir {
        if let hir::ExternalDeclaration::Declaration(hir::Declaration::InitDeclaratorList(ref d)) = i {
            match &state.sym(d.head.name).decl {
                hir::SymDecl::Global(storage, ..) if state.used_globals.borrow().contains(&d.head.name) => {
                    match storage {
                        hir::StorageClass::In => {
                            inputs.push(d.head.name);
                        }
                        hir::StorageClass::Out | hir::StorageClass::FragColor(_) => {
                            outputs.push(d.head.name);
                        }
                        _ => {}
                    }
                }
                _ => {}
            }
        }
    }

    let fn_info = compute_fn_info(&state, &hir);
    let const_inits = collect_const_inits(&state, &hir);
    let kind = if is_frag { ShaderKind::Fragment } else { ShaderKind::Vertex };
    let part_name = name.to_owned()
        + match kind {
            ShaderKind::Vertex => "_vert",
            ShaderKind::Fragment => "_frag",
        };

    let mut state = OutputState {
        hir: state,
        output: String::new(),
        buffer: RefCell::new(String::new()),
        indent: 0,
        mask: None,
        cond_index: 0,
        return_type: None,
        return_declared: false,
        return_vector: false,
        name: name.clone(),
        part_name: part_name.clone(),
        kind,
        functions: HashMap::new(),
        deps: RefCell::new(Vec::new()),
        vector_mask: 0,
        uses_discard: false,
        used_fragcoord: Cell::new(0),
        use_perspective: false,
        used_globals: RefCell::new(Vec::new()),
        texel_fetches: RefCell::new(Vec::new()),
        fn_info,
        const_inits,
        fn_names: RefCell::new(Vec::new()),
        out_params: RefCell::new(HashSet::new()),
        breaks: RefCell::new(Vec::new()),
        label_index: Cell::new(0),
        tmp_index: Cell::new(0),
        structs: RefCell::new(Vec::new()),
        fields: RefCell::new(Vec::new()),
        assoc: RefCell::new(Vec::new()),
        runtime: RefCell::new(BTreeSet::new()),
        requires: RefCell::new(BTreeSet::new()),
        uniform_list: uniform_indices.iter().map(|(n, (i, k, _))| (n.clone(), *i, *k)).collect(),
        attribs: Vec::new(),
    };

    // Global declarations: struct definitions, the stage struct's fields, associated consts.
    for ed in &hir {
        if let hir::ExternalDeclaration::Declaration(d) = ed {
            collect_global_declaration(&state, d);
        }
    }

    if state.kind == ShaderKind::Vertex {
        write_common_globals(&mut state, &inputs, &outputs, uniform_indices);
    }
    let common = state.finish_output();

    // The shader functions, reachable from the entry points, as in glsl-to-cxx.
    state.indent = 1;
    let mut functions = String::new();
    for fname in &["main", "swgl_drawSpanRGBA8", "swgl_drawSpanR8"] {
        if let Some(sym) = state.hir.lookup(fname) {
            show_function_variant(&mut state, sym, 0);
            functions.push_str(&state.finish_output());
        }
    }
    state.indent = 0;

    let pruned_inputs: Vec<_> = inputs.iter().filter(|i| state.used_globals.borrow().contains(i)).cloned().collect();
    state.attribs = pruned_inputs
        .iter()
        .map(|i| {
            let sym = state.hir.sym(*i);
            let flat = matches!(sym.decl, hir::SymDecl::Global(_, _, _, hir::RunClass::Scalar));
            (sym.name.clone(), flat)
        })
        .collect();

    write_stage_struct(&mut state, &pruned_inputs, &outputs);
    let mut body = common;
    body.push_str(&state.finish_output());

    let _ = writeln!(body, "impl {} {{", part_name);
    for a in state.assoc.borrow().iter() {
        body.push_str(a);
    }
    body.push_str(&functions);
    if state.kind == ShaderKind::Vertex {
        write_store_outputs(&mut state, &outputs);
    } else {
        write_read_inputs(&mut state, &pruned_inputs);
    }
    body.push_str(&state.finish_output());
    body.push_str("}\n\n");

    write_abi(&mut state);
    if state.kind == ShaderKind::Fragment {
        write_program(&mut state, uniform_indices);
    }
    body.push_str(&state.finish_output());

    let body = resolve_function_names(&state, body);
    let structs = state.structs.replace(Vec::new());
    StageOutput {
        structs: structs.into_iter().map(|(n, c)| (n.clone(), resolve_function_names(&state, c))).collect(),
        body,
        runtime: state.runtime.replace(BTreeSet::new()),
        requires: state.requires.replace(BTreeSet::new()),
    }
}

/// Replaces the placeholders written for user function names with the final names: the GLSL name when the
/// function has one variant (or for the all-scalar variant), else the name with a suffix naming the vector
/// parameters (`_v0_2`) and `_m` for the variant taking `_cond_mask_`. C++ overloads all variants on one name.
fn resolve_function_names(state: &OutputState, body: String) -> String {
    let names = state.fn_names.borrow();
    if names.is_empty() {
        return body;
    }
    let mut variants: HashMap<SymRef, BTreeSet<u32>> = HashMap::new();
    for (sym, mask) in names.iter() {
        variants.entry(*sym).or_default().insert(*mask);
    }
    let mut out = String::with_capacity(body.len());
    let mut rest = body.as_str();
    while let Some(start) = rest.find('\u{1}') {
        out.push_str(&rest[..start]);
        let end = start + rest[start..].find('\u{2}').unwrap();
        let idx: usize = rest[start + 1..end].parse().unwrap();
        let (sym, mask) = names[idx];
        let base = state.hir.sym(sym).name.clone();
        out.push_str(&rust_ident(&base));
        if variants[&sym].len() > 1 && mask != 0 {
            let params: Vec<String> = (0..31).filter(|i| mask & (1 << i) != 0).map(|i| i.to_string()).collect();
            if !params.is_empty() {
                let _ = write!(out, "_v{}", params.join("_"));
            }
            if mask & (1 << 31) != 0 {
                out.push_str("_m");
            }
        }
        rest = &rest[end + 1..];
    }
    out.push_str(rest);
    out
}

/// A target of `break`/`continue`.
#[derive(Clone, Copy)]
enum Brk {
    /// Loop `'l<N>`; a do-while (`true`) has its body in block `'do<N>`, which `continue` leaves.
    Loop(usize, bool),
    /// A scalar `switch`, block `'sw<N>`.
    Switch(usize),
    /// The body of a span shader that restores its interpolants on the way out, block `'body`.
    Body,
}

pub struct OutputState {
    hir: hir::State,
    output: String,
    buffer: RefCell<String>,
    indent: i32,
    mask: Option<Box<hir::Expr>>,
    cond_index: usize,
    return_type: Option<Box<hir::Type>>,
    return_declared: bool,
    return_vector: bool,
    name: String,
    part_name: String,
    kind: ShaderKind,
    functions: HashMap<(hir::SymRef, u32), bool>,
    deps: RefCell<Vec<(hir::SymRef, u32)>>,
    vector_mask: u32,
    uses_discard: bool,
    used_fragcoord: Cell<i32>,
    use_perspective: bool,
    used_globals: RefCell<Vec<hir::SymRef>>,
    texel_fetches: RefCell<Vec<(hir::SymRef, hir::SymRef, hir::TexelFetchOffsets)>>,
    fn_info: HashMap<SymRef, FnInfo>,
    const_inits: HashMap<SymRef, hir::Initializer>,
    /// Placeholder table for user function names: index -> (function, variant mask).
    fn_names: RefCell<Vec<(SymRef, u32)>>,
    /// The out/inout parameters of the function being written (read through `*`).
    out_params: RefCell<HashSet<SymRef>>,
    /// What `break` and `continue` leave, innermost last.
    breaks: RefCell<Vec<Brk>>,
    label_index: Cell<usize>,
    tmp_index: Cell<usize>,
    /// GLSL structs (name, Rust code).
    structs: RefCell<Vec<(String, String)>>,
    /// Fields of the stage struct (name, type).
    fields: RefCell<Vec<(String, String)>>,
    /// Associated consts and const functions of the stage struct.
    assoc: RefCell<Vec<String>>,
    runtime: RefCell<BTreeSet<(&'static str, String)>>,
    requires: RefCell<BTreeSet<String>>,
    /// (name, index, kind) of every uniform, for the `set_uniform_*` functions.
    uniform_list: Vec<(String, i32, hir::TypeKind)>,
    /// (name, flat) of the vertex attributes the shader reads.
    attribs: Vec<(String, bool)>,
}

impl OutputState {
    fn indent(&mut self) {
        self.indent += 1
    }
    fn outdent(&mut self) {
        self.indent -= 1
    }

    fn write(&self, s: &str) {
        self.buffer.borrow_mut().push_str(s);
    }

    fn flush_buffer(&mut self) {
        self.output.push_str(&self.buffer.borrow());
        self.buffer.borrow_mut().clear();
    }

    fn finish_output(&mut self) -> String {
        self.flush_buffer();

        let mut s = String::new();
        mem::swap(&mut self.output, &mut s);
        s
    }

    fn push_buffer(&self) -> String {
        self.buffer.replace(String::new())
    }

    fn pop_buffer(&self, s: String) -> String {
        self.buffer.replace(s)
    }

    fn write_fmt(&self, args: Arguments) {
        let _ = self.buffer.borrow_mut().write_fmt(args);
    }

    /// Records a name the emitted code takes from runtime module `module`, and returns it.
    fn rt(&self, module: &'static str, name: &str) -> String {
        self.runtime.borrow_mut().insert((module, name.to_string()));
        name.to_string()
    }

    fn require(&self, what: String) {
        self.requires.borrow_mut().insert(what);
    }

    fn tmp(&self, prefix: &str) -> String {
        let n = self.tmp_index.get();
        self.tmp_index.set(n + 1);
        format!("_{}{}_", prefix, n)
    }

    fn info(&self, sym: SymRef) -> FnInfo {
        self.fn_info.get(&sym).copied().unwrap_or_default()
    }

    /// A placeholder for the name of variant `mask` of user function `sym`, resolved by
    /// [`resolve_function_names`].
    fn fn_name(&self, sym: SymRef, mask: u32) -> String {
        let mut names = self.fn_names.borrow_mut();
        let idx = match names.iter().position(|&(s, m)| s == sym && m == mask) {
            Some(i) => i,
            None => {
                names.push((sym, mask));
                names.len() - 1
            }
        };
        format!("\u{1}{}\u{2}", idx)
    }
}

const RUST_KEYWORDS: &[&str] = &[
    "as", "break", "const", "continue", "crate", "else", "enum", "extern", "false", "fn", "for", "if", "impl", "in",
    "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return", "self", "Self", "static", "struct", "super",
    "trait", "true", "type", "unsafe", "use", "where", "while", "async", "await", "dyn", "abstract", "become", "box",
    "do", "final", "macro", "override", "priv", "typeof", "unsized", "virtual", "yield", "try", "gen",
];

/// A GLSL identifier as a Rust identifier (`mod` is `r#mod`).
fn rust_ident(name: &str) -> String {
    if RUST_KEYWORDS.contains(&name) {
        format!("r#{}", name)
    } else {
        name.to_string()
    }
}

fn add_used_global(state: &OutputState, i: &hir::SymRef) {
    let mut globals = state.used_globals.borrow_mut();
    if !globals.contains(i) {
        globals.push(*i);
    }
}

// ---- types ------------------------------------------------------------------------------------------------------

fn scalar_prim(k: &TypeKind) -> Option<&'static str> {
    Some(match k {
        TypeKind::Void => "()",
        TypeKind::Bool => "bool",
        TypeKind::Int => "i32",
        TypeKind::UInt => "u32",
        TypeKind::Float => "f32",
        TypeKind::Double => "f64",
        _ => return None,
    })
}

fn lane_prim(k: &TypeKind) -> Option<&'static str> {
    Some(match k {
        TypeKind::Bool => "Bool",
        TypeKind::Int => "I32",
        TypeKind::UInt => "U32",
        TypeKind::Float => "Float",
        TypeKind::Double => "Double",
        _ => return None,
    })
}

/// The element kind of a vector or matrix kind (`Vec3` -> `Float`), or the kind itself for scalars.
fn elem_kind(k: TypeKind) -> TypeKind {
    use TypeKind::*;
    match k {
        Vec2 | Vec3 | Vec4 | Mat2 | Mat3 | Mat4 | Mat23 | Mat24 | Mat32 | Mat34 | Mat42 | Mat43 => Float,
        DVec2 | DVec3 | DVec4 => Double,
        BVec2 | BVec3 | BVec4 => Bool,
        IVec2 | IVec3 | IVec4 => Int,
        UVec2 | UVec3 | UVec4 => UInt,
        k => k,
    }
}

fn is_scalar_kind(k: TypeKind) -> bool {
    matches!(k, TypeKind::Bool | TypeKind::Int | TypeKind::UInt | TypeKind::Float | TypeKind::Double)
}

fn is_vec_kind(k: TypeKind) -> bool {
    use TypeKind::*;
    matches!(
        k,
        Vec2 | Vec3
            | Vec4
            | DVec2
            | DVec3
            | DVec4
            | BVec2
            | BVec3
            | BVec4
            | IVec2
            | IVec3
            | IVec4
            | UVec2
            | UVec3
            | UVec4
    )
}

fn is_matrix_kind(k: TypeKind) -> bool {
    use TypeKind::*;
    matches!(k, Mat2 | Mat3 | Mat4 | Mat23 | Mat24 | Mat32 | Mat34 | Mat42 | Mat43)
}

fn is_float_kind(k: TypeKind) -> bool {
    matches!(k, TypeKind::Float | TypeKind::Double)
}

fn is_int_kind(k: TypeKind) -> bool {
    matches!(k, TypeKind::Int | TypeKind::UInt)
}

/// Replaces the element kind of `k` (`IVec2` with `Float` -> `Vec2`).
fn with_elem(k: TypeKind, e: TypeKind) -> TypeKind {
    use TypeKind::*;
    let n = match k {
        Vec2 | DVec2 | BVec2 | IVec2 | UVec2 => 2,
        Vec3 | DVec3 | BVec3 | IVec3 | UVec3 => 3,
        Vec4 | DVec4 | BVec4 | IVec4 | UVec4 => 4,
        _ => return e,
    };
    match (e, n) {
        (Float, 2) => Vec2,
        (Float, 3) => Vec3,
        (Float, 4) => Vec4,
        (Double, 2) => DVec2,
        (Double, 3) => DVec3,
        (Double, 4) => DVec4,
        (Bool, 2) => BVec2,
        (Bool, 3) => BVec3,
        (Bool, 4) => BVec4,
        (Int, 2) => IVec2,
        (Int, 3) => IVec3,
        (Int, 4) => IVec4,
        (UInt, 2) => UVec2,
        (UInt, 3) => UVec3,
        (UInt, 4) => UVec4,
        _ => k,
    }
}

/// The Rust name of a type kind, scalar (`vec4_scalar`, `f32`) or lanes (`vec4`, `Float`), without recording it.
fn kind_str(state: &OutputState, t: &TypeKind, scalar: bool) -> String {
    if let Some(n) = if scalar { scalar_prim(t) } else { lane_prim(t) } {
        return n.to_string();
    }
    if *t == TypeKind::Void {
        return "()".to_string();
    }
    if t.is_sampler() {
        return t.glsl_primitive_type_name().unwrap().to_string();
    }
    if let Some(n) = t.glsl_primitive_type_name() {
        return if scalar { format!("{}_scalar", n) } else { n.to_string() };
    }
    match t {
        TypeKind::Struct(s) => {
            let n = state.hir.sym(*s).name.clone();
            if scalar {
                format!("{}_scalar", n)
            } else {
                n
            }
        }
        _ => unreachable!(),
    }
}

/// Like [`kind_str`], recording runtime type names for the `use` lines.
fn kind_name(state: &OutputState, t: &TypeKind, scalar: bool) -> String {
    let s = kind_str(state, t, scalar);
    if !matches!(t, TypeKind::Struct(_)) && !(scalar && scalar_prim(t).is_some()) && *t != TypeKind::Void {
        state.rt("glsl", &s);
    }
    s
}

fn array_len(state: &OutputState, t: &Type) -> Option<usize> {
    t.array_sizes.as_ref().map(|a| match &a.sizes[..] {
        [size] => const_int(state, size).expect("array size must be a constant") as usize,
        _ => panic!("multidimensional arrays are not supported"),
    })
}

/// The Rust type of a GLSL type (`[vec4_scalar; 2]` for `Array<vec4_scalar,2>`).
fn type_name(state: &OutputState, t: &Type, scalar: bool) -> String {
    let k = kind_name(state, &t.kind, scalar);
    match array_len(state, t) {
        Some(n) => format!("[{}; {}]", k, n),
        None => k,
    }
}

fn type_str(state: &OutputState, t: &Type, scalar: bool) -> String {
    let k = kind_str(state, &t.kind, scalar);
    match array_len(state, t) {
        Some(n) => format!("[{}; {}]", k, n),
        None => k,
    }
}

/// The value of a constant integer expression (a literal or a global `const` with a literal initializer).
fn const_int(state: &OutputState, e: &hir::Expr) -> Option<i64> {
    match &e.kind {
        hir::ExprKind::IntConst(x) => Some(*x as i64),
        hir::ExprKind::UIntConst(x) => Some(*x as i64),
        hir::ExprKind::Unary(UnaryOp::Minus, e) => const_int(state, e).map(|x| -x),
        hir::ExprKind::Variable(s) => match state.const_inits.get(s) {
            Some(hir::Initializer::Simple(e)) => const_int(state, e),
            _ => None,
        },
        _ => None,
    }
}

// ---- run classes ------------------------------------------------------------------------------------------------

fn symbol_run_class(decl: &hir::SymDecl, vector_mask: u32) -> hir::RunClass {
    let run_class = match decl {
        hir::SymDecl::Global(_, _, _, run_class) => *run_class,
        hir::SymDecl::Local(_, _, run_class) => *run_class,
        _ => hir::RunClass::Vector,
    };
    match run_class {
        hir::RunClass::Scalar => hir::RunClass::Scalar,
        hir::RunClass::Dependent(mask) => {
            if (mask & vector_mask) != 0 {
                hir::RunClass::Vector
            } else {
                hir::RunClass::Scalar
            }
        }
        _ => hir::RunClass::Vector,
    }
}

fn expr_run_class(state: &OutputState, expr: &hir::Expr) -> hir::RunClass {
    match &expr.kind {
        hir::ExprKind::Variable(i) => symbol_run_class(&state.hir.sym(*i).decl, state.vector_mask),
        hir::ExprKind::IntConst(_)
        | hir::ExprKind::UIntConst(_)
        | hir::ExprKind::BoolConst(_)
        | hir::ExprKind::FloatConst(_)
        | hir::ExprKind::DoubleConst(_) => hir::RunClass::Scalar,
        hir::ExprKind::Unary(_, ref e) => expr_run_class(state, e),
        hir::ExprKind::Binary(_, ref l, ref r) => expr_run_class(state, l).merge(expr_run_class(state, r)),
        hir::ExprKind::Ternary(ref c, ref s, ref e) => {
            expr_run_class(state, c).merge(expr_run_class(state, s)).merge(expr_run_class(state, e))
        }
        hir::ExprKind::Assignment(ref v, _, ref e) => expr_run_class(state, v).merge(expr_run_class(state, e)),
        hir::ExprKind::Bracket(ref e, ref indx) => {
            indx.iter().fold(expr_run_class(state, e), |run_class, indx| run_class.merge(expr_run_class(state, indx)))
        }
        hir::ExprKind::FunCall(ref fun, ref args) => {
            let arg_mask: u32 = args.iter().enumerate().fold(0, |mask, (idx, e)| {
                if expr_run_class(state, e) == hir::RunClass::Vector {
                    mask | (1 << idx)
                } else {
                    mask
                }
            });
            match fun {
                hir::FunIdentifier::Identifier(ref sym) => match &state.hir.sym(*sym).decl {
                    hir::SymDecl::NativeFunction(_, _, ref ret_class) => {
                        if *ret_class != hir::RunClass::Unknown {
                            *ret_class
                        } else if arg_mask != 0 {
                            hir::RunClass::Vector
                        } else {
                            hir::RunClass::Scalar
                        }
                    }
                    hir::SymDecl::UserFunction(ref fd, ref run_class) => {
                        let param_mask: u32 =
                            fd.prototype.parameters.iter().enumerate().fold(arg_mask, |mask, (idx, param)| {
                                if let hir::FunctionParameterDeclaration::Named(Some(qual), p) = param {
                                    match qual {
                                        hir::ParameterQualifier::InOut | hir::ParameterQualifier::Out => {
                                            if symbol_run_class(&state.hir.sym(p.sym).decl, arg_mask)
                                                == hir::RunClass::Vector
                                            {
                                                mask | (1 << idx)
                                            } else {
                                                mask
                                            }
                                        }
                                        _ => mask,
                                    }
                                } else {
                                    mask
                                }
                            });
                        match *run_class {
                            hir::RunClass::Scalar => hir::RunClass::Scalar,
                            hir::RunClass::Dependent(mask) => {
                                if (mask & param_mask) != 0 {
                                    hir::RunClass::Vector
                                } else {
                                    hir::RunClass::Scalar
                                }
                            }
                            _ => hir::RunClass::Vector,
                        }
                    }
                    hir::SymDecl::Struct(..) => {
                        if arg_mask != 0 {
                            hir::RunClass::Vector
                        } else {
                            hir::RunClass::Scalar
                        }
                    }
                    _ => panic!(),
                },
                hir::FunIdentifier::Constructor(..) => {
                    if arg_mask != 0 {
                        hir::RunClass::Vector
                    } else {
                        hir::RunClass::Scalar
                    }
                }
            }
        }
        hir::ExprKind::Dot(ref e, _) => expr_run_class(state, e),
        hir::ExprKind::SwizzleSelector(ref e, _) => expr_run_class(state, e),
        hir::ExprKind::PostInc(ref e) => expr_run_class(state, e),
        hir::ExprKind::PostDec(ref e) => expr_run_class(state, e),
        hir::ExprKind::Comma(_, ref e) => expr_run_class(state, e),
        hir::ExprKind::Cond(_, ref e) => expr_run_class(state, e),
        hir::ExprKind::CondMask => hir::RunClass::Vector,
    }
}

fn is_vec(state: &OutputState, e: &hir::Expr) -> bool {
    expr_run_class(state, e) == hir::RunClass::Vector
}

// ---- literals and conversions -----------------------------------------------------------------------------------

fn float_lit(x: f32) -> String {
    if x.is_nan() {
        "f32::NAN".to_string()
    } else if x.is_infinite() {
        if x > 0.0 { "f32::INFINITY" } else { "f32::NEG_INFINITY" }.to_string()
    } else if x < 0.0 || (x == 0.0 && x.is_sign_negative()) {
        format!("({:?}f32)", x)
    } else {
        format!("{:?}f32", x)
    }
}

/// Whether `code` can take a `.field` or `.method()` without parentheses.
fn is_simple(code: &str) -> bool {
    let mut chars = code.chars();
    match chars.next() {
        Some(c) if c.is_ascii_alphabetic() || c == '_' => {}
        _ => return false,
    }
    code.chars().all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '.' || c == '#')
}

fn paren(code: String) -> String {
    if is_simple(&code) {
        code
    } else {
        format!("({})", code)
    }
}

/// Spells out the conversion C++ did implicitly from (`from`, `from_vec`) to (`to`, `to_vec`): an int-to-float
/// kind change (`as f32`, `make_float`, `make_vecN`), then a lane promotion (`T::from`) or `force_scalar`.
fn convert(
    state: &OutputState,
    code: String,
    e: Option<&hir::Expr>,
    from: &Type,
    from_vec: bool,
    to: &Type,
    to_vec: bool,
) -> String {
    let mut code = code;
    let mut cur = from.clone();
    if from.array_sizes.is_none() && to.array_sizes.is_none() && from.kind != to.kind {
        if let Some(c) = kind_convert(state, &code, e, from.kind, to.kind, from_vec) {
            code = c;
            cur = Type::new(to.kind);
        }
    }
    if !from_vec && to_vec {
        code = promote(state, code, &cur);
    } else if from_vec && !to_vec {
        let s = type_str(state, &cur, true);
        state.require(format!("force_scalar({}) -> {}", type_str(state, &cur, false), s));
        code = format!("{}({})", state.rt("glsl", "force_scalar"), code);
    }
    code
}

fn kind_convert(
    state: &OutputState,
    code: &str,
    e: Option<&hir::Expr>,
    from: TypeKind,
    to: TypeKind,
    vec: bool,
) -> Option<String> {
    use TypeKind::*;
    match (from, to) {
        (Int | UInt, Float | Double) => {
            if let Some(e) = e {
                match e.kind {
                    hir::ExprKind::IntConst(x) => return Some(float_lit(x as f32)),
                    hir::ExprKind::UIntConst(x) => return Some(float_lit(x as f32)),
                    _ => {}
                }
            }
            if vec {
                Some(format!("{}({})", state.rt("glsl", "make_float"), code))
            } else {
                Some(format!("({} as f32)", paren(code.to_string())))
            }
        }
        (IVec2 | UVec2, Vec2) => Some(format!("{}({})", state.rt("glsl", "make_vec2"), code)),
        (IVec3 | UVec3, Vec3) => Some(format!("{}({})", state.rt("glsl", "make_vec3"), code)),
        (IVec4 | UVec4, Vec4) => Some(format!("{}({})", state.rt("glsl", "make_vec4"), code)),
        (Vec2, IVec2) => Some(format!("{}({})", state.rt("glsl", "make_ivec2"), code)),
        _ => None,
    }
}

/// `T::from(x)`: a scalar value broadcast to every lane.
fn promote(state: &OutputState, code: String, ty: &Type) -> String {
    if ty.array_sizes.is_some() {
        let elem = kind_str(state, &ty.kind, false);
        kind_name(state, &ty.kind, false);
        state.require(format!("{}::from({})", elem, kind_str(state, &ty.kind, true)));
        return format!("{}.map({}::from)", paren(code), elem);
    }
    let v = type_name(state, ty, false);
    if ty.kind == TypeKind::Bool {
        // C++ splats `int(b)`: 1 in every lane, not the -1 of a comparison mask.
        state.require(format!("{}::from(i32)", v));
        return format!("{}::from(({}) as i32)", v, code);
    }
    if !matches!(ty.kind, TypeKind::Struct(_)) {
        state.require(format!("{}::from({})", v, type_str(state, ty, true)));
    }
    format!("{}::from({})", v, code)
}

/// `e` converted to type `to`, lanes if `to_vec`.
fn ex_to(state: &OutputState, e: &hir::Expr, to: &Type, to_vec: bool) -> String {
    let from_vec = is_vec(state, e);
    // Literals in a float context are written as float literals.
    if is_float_kind(to.kind) && to.array_sizes.is_none() {
        let lit = match e.kind {
            hir::ExprKind::IntConst(x) => Some(float_lit(x as f32)),
            hir::ExprKind::UIntConst(x) => Some(float_lit(x as f32)),
            _ => None,
        };
        if let Some(lit) = lit {
            return if to_vec { promote(state, lit, &Type::new(to.kind)) } else { lit };
        }
    }
    let code = ex(state, e);
    convert(state, code, Some(e), &e.ty, from_vec, to, to_vec)
}

/// The constant 1 of a type, for `++`/`--`.
fn one(state: &OutputState, ty: &Type, vec: bool) -> String {
    let lit = match elem_kind(ty.kind) {
        TypeKind::Float | TypeKind::Double => "1.0f32".to_string(),
        TypeKind::UInt => "1u32".to_string(),
        _ => "1".to_string(),
    };
    if vec {
        promote(state, lit, &Type::new(elem_kind(ty.kind)))
    } else {
        lit
    }
}

// ---- symbols ----------------------------------------------------------------------------------------------------

/// How the emitted code reads a symbol.
fn show_sym(state: &OutputState, i: &hir::SymRef) -> String {
    let sym = state.hir.sym(*i);
    match &sym.decl {
        hir::SymDecl::NativeFunction(_, ref cxx_name, _) => cxx_name.unwrap_or(sym.name.as_str()).to_string(),
        hir::SymDecl::Global(storage, ..) => {
            add_used_global(state, i);
            match sym.name.as_str() {
                "gl_FragCoord" => return "self.fs.gl_FragCoord".into(),
                "gl_FragColor" => return "self.fs.gl_FragColor".into(),
                "gl_Position" => return "self.vs.gl_Position".into(),
                "gl_ClipDistance" => return "self.vs.gl_ClipDistance".into(),
                "swgl_SpanLength" => return "self.fs.swgl_SpanLength".into(),
                "swgl_StepSize" => return state.rt("program", "swgl_StepSize"),
                _ => {}
            }
            match storage {
                hir::StorageClass::FragColor(0) => "self.fs.gl_FragColor".into(),
                hir::StorageClass::FragColor(1) => "self.fs.gl_SecondaryFragColor".into(),
                hir::StorageClass::FragColor(_) => panic!("bad fragment output index"),
                hir::StorageClass::Out if state.kind == ShaderKind::Fragment => "self.fs.gl_FragColor".into(),
                hir::StorageClass::Const => {
                    if const_is_literal(state, *i) {
                        format!("Self::{}", sym.name)
                    } else {
                        format!("Self::{}()", sym.name)
                    }
                }
                _ => format!("self.{}", rust_ident(&sym.name)),
            }
        }
        hir::SymDecl::Local(..) => {
            if state.out_params.borrow().contains(i) {
                format!("*{}", rust_ident(&sym.name))
            } else {
                rust_ident(&sym.name)
            }
        }
        hir::SymDecl::UserFunction(..) | hir::SymDecl::Struct(..) => rust_ident(&sym.name),
    }
}

fn is_literal(e: &hir::Expr) -> bool {
    match &e.kind {
        hir::ExprKind::IntConst(_)
        | hir::ExprKind::UIntConst(_)
        | hir::ExprKind::BoolConst(_)
        | hir::ExprKind::FloatConst(_)
        | hir::ExprKind::DoubleConst(_) => true,
        hir::ExprKind::Unary(UnaryOp::Minus, e) => is_literal(e),
        _ => false,
    }
}

/// Global consts with a literal initializer become associated `const`s, the others (`make_mat3(...)`)
/// associated functions.
fn const_is_literal(state: &OutputState, sym: SymRef) -> bool {
    match state.const_inits.get(&sym) {
        Some(hir::Initializer::Simple(e)) => is_literal(e),
        _ => false,
    }
}

// ---- expressions ------------------------------------------------------------------------------------------------

fn show_hir_expr(state: &OutputState, expr: &hir::Expr) -> String {
    ex(state, expr)
}

fn ex(state: &OutputState, expr: &hir::Expr) -> String {
    ex_inner(state, expr, false)
}

/// The Rust for a GLSL expression. `top_level` is set for an expression statement, where assignments and
/// calls need not produce a value.
fn ex_inner(state: &OutputState, expr: &hir::Expr, top_level: bool) -> String {
    match expr.kind {
        hir::ExprKind::Variable(ref i) => show_sym(state, i),
        hir::ExprKind::IntConst(x) => {
            if x < 0 {
                format!("({})", x)
            } else {
                x.to_string()
            }
        }
        hir::ExprKind::UIntConst(x) => format!("{}u32", x),
        hir::ExprKind::BoolConst(x) => x.to_string(),
        hir::ExprKind::FloatConst(x) => float_lit(x),
        hir::ExprKind::DoubleConst(x) => float_lit(x as f32),
        hir::ExprKind::Unary(ref op, ref e) => match op {
            UnaryOp::Inc | UnaryOp::Dec => {
                let rv = ex(state, e);
                let value = format!(
                    "({}) {} ({})",
                    rv,
                    if *op == UnaryOp::Inc { "+" } else { "-" },
                    one(state, &e.ty, is_vec(state, e))
                );
                let store = store(state, e, value);
                if top_level {
                    store
                } else {
                    format!("{{ {}; {} }}", store, rv)
                }
            }
            UnaryOp::Add => format!("({})", ex(state, e)),
            UnaryOp::Minus => {
                let t = type_str(state, &e.ty, !is_vec(state, e));
                if !(scalar_prim(&e.ty.kind).is_some() && !is_vec(state, e)) {
                    state.require(format!("impl Neg for {}", t));
                }
                format!("-({})", ex(state, e))
            }
            UnaryOp::Not | UnaryOp::Complement => {
                let t = type_str(state, &e.ty, !is_vec(state, e));
                if !(scalar_prim(&e.ty.kind).is_some() && !is_vec(state, e)) {
                    state.require(format!("impl Not for {}", t));
                }
                format!("!({})", ex(state, e))
            }
        },
        hir::ExprKind::Binary(ref op, ref l, ref r) => emit_binary(state, op, l, r, &expr.ty),
        hir::ExprKind::Ternary(ref c, ref s, ref e) => {
            let v = is_vec(state, c) || is_vec(state, s) || is_vec(state, e);
            let cc = ex(state, c);
            let sc = ex_to(state, s, &expr.ty, v);
            let ec = ex_to(state, e, &expr.ty, v);
            if is_vec(state, c) {
                state.require(format!("if_then_else(Bool, {0}, {0})", type_str(state, &expr.ty, !v)));
                format!("{}({}, {}, {})", state.rt("glsl", "if_then_else"), cc, sc, ec)
            } else {
                format!("if {} {{ {} }} else {{ {} }}", cc, sc, ec)
            }
        }
        hir::ExprKind::Assignment(ref v, ref op, ref e) => emit_assignment(state, v, op, e, top_level),
        hir::ExprKind::Bracket(ref e, ref indx) => {
            let mut code = ex(state, e);
            let mut ty = e.ty.clone();
            let base_vec = is_vec(state, e);
            for dimension in indx {
                code = index_expr(state, code, &ty, base_vec, dimension);
                ty = Type::new(ty.kind);
            }
            code
        }
        hir::ExprKind::FunCall(ref fun, ref args) => emit_call(state, expr, fun, args, top_level),
        hir::ExprKind::Dot(ref e, ref i) => format!("{}.{}", paren(ex(state, e)), i.as_str()),
        hir::ExprKind::SwizzleSelector(ref e, ref s) => {
            if let hir::ExprKind::Variable(ref sym) = &e.kind {
                if state.hir.sym(*sym).name == "gl_FragCoord" {
                    state
                        .used_fragcoord
                        .set(s.components.iter().fold(state.used_fragcoord.get(), |used, c| used | (1 << c)));
                }
            }
            let base = paren(ex(state, e));
            if s.components.len() == 1 {
                // For single component swizzles, output a field access, as the C++ does.
                format!("{}.{}", base, s.to_field_set(hir::FieldSet::Xyzw))
            } else {
                let comps: Vec<String> =
                    s.to_string().chars().map(|c| state.rt("glsl", &c.to_uppercase().to_string())).collect();
                state.require(format!(
                    "{}::sel{}({}) -> {}",
                    type_str(state, &e.ty, !is_vec(state, e)),
                    comps.len(),
                    vec!["XYZW"; comps.len()].join(", "),
                    type_str(state, &expr.ty, !is_vec(state, e))
                ));
                format!("{}.sel{}({})", base, comps.len(), comps.join(", "))
            }
        }
        hir::ExprKind::PostInc(ref e) | hir::ExprKind::PostDec(ref e) => {
            let inc = matches!(expr.kind, hir::ExprKind::PostInc(_));
            let rv = ex(state, e);
            let value = format!("({}) {} ({})", rv, if inc { "+" } else { "-" }, one(state, &e.ty, is_vec(state, e)));
            let store = store(state, e, value);
            if top_level {
                store
            } else {
                let t = state.tmp("t");
                format!("{{ let {} = {}; {}; {} }}", t, rv, store, t)
            }
        }
        hir::ExprKind::Comma(ref a, ref b) => {
            format!("{{ {}; {} }}", ex_inner(state, a, true), ex(state, b))
        }
        hir::ExprKind::Cond(index, _) => format!("_c{}_", index),
        hir::ExprKind::CondMask => "_cond_mask_".to_string(),
    }
}

/// Indexing: arrays and matrices by a scalar, vectors by a scalar or by lanes (`index_lanes`). `base_vec`: the
/// indexed value is lanes.
fn index_expr(state: &OutputState, base: String, ty: &Type, base_vec: bool, idx: &hir::Expr) -> String {
    if is_vec(state, idx) {
        let i = ex_to(state, idx, &Type::new(TypeKind::Int), true);
        if ty.array_sizes.is_some() {
            state.require(format!("index_array_lanes(&{}, I32)", type_str(state, ty, true)));
            return format!("{}(&{}, {})", state.rt("glsl", "index_array_lanes"), base, i);
        }
        state.require(format!("{}::index_lanes(I32)", type_str(state, ty, !base_vec)));
        return format!("{}.index_lanes({})", paren(base), i);
    }
    let i = match const_int(state, idx) {
        Some(n) if matches!(idx.kind, hir::ExprKind::IntConst(_) | hir::ExprKind::UIntConst(_)) => n.to_string(),
        _ => format!("({}) as usize", ex(state, idx)),
    };
    if ty.array_sizes.is_none() && !is_scalar_kind(ty.kind) {
        state.require(format!("impl Index<usize> + IndexMut<usize> for {}", kind_str(state, &ty.kind, !base_vec)));
    }
    format!("{}[{}]", paren(base), i)
}

/// An assignable place.
enum LValue {
    Place(String),
    /// A swizzle of more than one component: written with `lselN(...).assign(v)`.
    Swizzle(String, Vec<String>),
}

fn lvalue(state: &OutputState, e: &hir::Expr) -> LValue {
    match &e.kind {
        hir::ExprKind::Variable(_) => LValue::Place(ex(state, e)),
        hir::ExprKind::Dot(b, f) => match lvalue(state, b) {
            LValue::Place(p) => LValue::Place(format!("{}.{}", paren(p), f.as_str())),
            LValue::Swizzle(..) => panic!("field of a swizzle"),
        },
        hir::ExprKind::SwizzleSelector(b, s) => {
            let base = match lvalue(state, b) {
                LValue::Place(p) => p,
                LValue::Swizzle(..) => panic!("swizzle of a swizzle"),
            };
            if s.components.len() == 1 {
                LValue::Place(format!("{}.{}", paren(base), s.to_field_set(hir::FieldSet::Xyzw)))
            } else {
                LValue::Swizzle(
                    base,
                    s.to_string().chars().map(|c| state.rt("glsl", &c.to_uppercase().to_string())).collect(),
                )
            }
        }
        hir::ExprKind::Bracket(b, idx) => {
            let mut p = match lvalue(state, b) {
                LValue::Place(p) => p,
                LValue::Swizzle(..) => panic!("index of a swizzle"),
            };
            let mut ty = b.ty.clone();
            for i in idx {
                if is_vec(state, i) {
                    panic!("assignment through a lane index");
                }
                p = index_expr(state, p, &ty, is_vec(state, b), i);
                ty = Type::new(ty.kind);
            }
            LValue::Place(p)
        }
        _ => panic!("not an lvalue: {:?}", e.kind),
    }
}

/// `place = value`. A multi-component swizzle evaluates the value first, since the `lselN` proxy borrows the
/// vector.
fn store(state: &OutputState, place: &hir::Expr, value: String) -> String {
    match lvalue(state, place) {
        LValue::Place(p) => format!("{} = {}", p, value),
        LValue::Swizzle(b, comps) => {
            let t = state.tmp("v");
            format!("{{ let {} = {}; {}.lsel{}({}).assign({}) }}", t, value, paren(b), comps.len(), comps.join(", "), t)
        }
    }
}

/// The root variable of a place, and whether the place is reached through a swizzle.
fn place_root(e: &hir::Expr) -> Option<(SymRef, bool)> {
    match &e.kind {
        hir::ExprKind::Variable(s) => Some((*s, false)),
        hir::ExprKind::Dot(b, _) => place_root(b),
        hir::ExprKind::Bracket(b, _) => place_root(b),
        hir::ExprKind::SwizzleSelector(b, sel) => {
            place_root(b).map(|(s, swizzled)| (s, swizzled || sel.components.len() > 1))
        }
        _ => None,
    }
}

fn binary_op_str(op: &syntax::BinaryOp) -> &'static str {
    match *op {
        syntax::BinaryOp::Or => "||",
        syntax::BinaryOp::Xor => "^",
        syntax::BinaryOp::And => "&&",
        syntax::BinaryOp::BitOr => "|",
        syntax::BinaryOp::BitXor => "^",
        syntax::BinaryOp::BitAnd => "&",
        syntax::BinaryOp::Equal => "==",
        syntax::BinaryOp::NonEqual => "!=",
        syntax::BinaryOp::LT => "<",
        syntax::BinaryOp::GT => ">",
        syntax::BinaryOp::LTE => "<=",
        syntax::BinaryOp::GTE => ">=",
        syntax::BinaryOp::LShift => "<<",
        syntax::BinaryOp::RShift => ">>",
        syntax::BinaryOp::Add => "+",
        syntax::BinaryOp::Sub => "-",
        syntax::BinaryOp::Mult => "*",
        syntax::BinaryOp::Div => "/",
        syntax::BinaryOp::Mod => "%",
    }
}

fn op_trait(op: &str) -> &'static str {
    match op {
        "+" => "Add",
        "-" => "Sub",
        "*" => "Mul",
        "/" => "Div",
        "%" => "Rem",
        "&" => "BitAnd",
        "|" => "BitOr",
        "^" => "BitXor",
        "<<" => "Shl",
        ">>" => "Shr",
        _ => "?",
    }
}

/// The type an operand of an arithmetic operator is converted to: its own, except that an int operand of a float
/// operation becomes float (C++ converted it implicitly).
fn arith_operand_type(side: &Type, result: &Type) -> Type {
    let se = elem_kind(side.kind);
    let re = elem_kind(result.kind);
    if side.array_sizes.is_none() && is_int_kind(se) && is_float_kind(re) {
        if is_scalar_kind(side.kind) {
            return Type::new(re);
        }
        if is_vec_kind(side.kind) {
            return Type::new(with_elem(side.kind, re));
        }
    }
    side.clone()
}

/// `l op r` with both operands in `vec` run class, as Rust: arithmetic and bit operators through `std::ops`,
/// comparisons of lanes through `lessThan` & co (they give a mask), `cmp_eq`/`cmp_ne` for vectors of lanes.
fn binary_code(
    state: &OutputState,
    op: &syntax::BinaryOp,
    l: &hir::Expr,
    r: &hir::Expr,
    result: &Type,
    vec: bool,
) -> String {
    use syntax::BinaryOp::*;
    match op {
        Or | And | Xor => {
            let b = Type::new(TypeKind::Bool);
            let lc = ex_to(state, l, &b, vec);
            let rc = ex_to(state, r, &b, vec);
            let o = if vec {
                match op {
                    Or => "|",
                    And => "&",
                    _ => "^",
                }
            } else {
                match op {
                    Or => "||",
                    And => "&&",
                    _ => "!=",
                }
            };
            format!("({}) {} ({})", lc, o, rc)
        }
        Equal | NonEqual | LT | GT | LTE | GTE => {
            // Compare in the float kind when one side is int.
            let (lt, rt) = if is_float_kind(elem_kind(l.ty.kind)) && is_int_kind(elem_kind(r.ty.kind)) {
                (l.ty.clone(), arith_operand_type(&r.ty, &l.ty))
            } else if is_float_kind(elem_kind(r.ty.kind)) && is_int_kind(elem_kind(l.ty.kind)) {
                (arith_operand_type(&l.ty, &r.ty), r.ty.clone())
            } else {
                (l.ty.clone(), r.ty.clone())
            };
            let lc = ex_to(state, l, &lt, vec);
            let rc = ex_to(state, r, &rt, vec);
            if !vec {
                return format!("({}) {} ({})", lc, binary_op_str(op), rc);
            }
            if is_vec_kind(lt.kind) || matches!(lt.kind, TypeKind::Struct(_)) || lt.array_sizes.is_some() {
                let m = match op {
                    Equal => "cmp_eq",
                    NonEqual => "cmp_ne",
                    _ => panic!("ordering comparison of vectors"),
                };
                state.require(format!(
                    "{}::{}(&{}) -> I32",
                    type_str(state, &lt, false),
                    m,
                    type_str(state, &rt, false)
                ));
                return format!("{}.{}(&{})", paren(lc), m, rc);
            }
            let f = match op {
                Equal => "equal",
                NonEqual => "notEqual",
                LT => "lessThan",
                GT => "greaterThan",
                LTE => "lessThanEqual",
                _ => "greaterThanEqual",
            };
            state.require(format!("{}({}, {})", f, type_str(state, &lt, false), type_str(state, &rt, false)));
            format!("{}({}, {})", state.rt("glsl", f), lc, rc)
        }
        _ => {
            let (lt, rt) = if *op == Mult && !is_scalar_kind(elem_kind(l.ty.kind)) {
                (l.ty.clone(), r.ty.clone())
            } else {
                (arith_operand_type(&l.ty, result), arith_operand_type(&r.ty, result))
            };
            // A matrix product keeps each side's run class (C++ has `mat4_scalar * vec4`, same formula, no
            // broadcast of the matrix).
            let matrix = *op == Mult && (is_matrix_kind(l.ty.kind) || is_matrix_kind(r.ty.kind));
            let (lv, rv) = if matrix { (is_vec(state, l), is_vec(state, r)) } else { (vec, vec) };
            let lc = ex_to(state, l, &lt, lv);
            let rc = ex_to(state, r, &rt, rv);
            let o = binary_op_str(op);
            let ls = type_str(state, &lt, !lv);
            let rs = type_str(state, &rt, !rv);
            if !(scalar_prim(&lt.kind).is_some() && lt.kind == rt.kind && !vec) {
                state.require(format!("impl {}<{}> for {}", op_trait(o), rs, ls));
            }
            format!("({}) {} ({})", lc, o, rc)
        }
    }
}

fn emit_binary(state: &OutputState, op: &syntax::BinaryOp, l: &hir::Expr, r: &hir::Expr, ty: &Type) -> String {
    let vec = is_vec(state, l) || is_vec(state, r);
    binary_code(state, op, l, r, ty, vec)
}

fn assignment_binary_op(op: &syntax::AssignmentOp) -> Option<syntax::BinaryOp> {
    use syntax::AssignmentOp as A;
    use syntax::BinaryOp as B;
    Some(match op {
        A::Equal => return None,
        A::Mult => B::Mult,
        A::Div => B::Div,
        A::Mod => B::Mod,
        A::Add => B::Add,
        A::Sub => B::Sub,
        A::LShift => B::LShift,
        A::RShift => B::RShift,
        A::And => B::BitAnd,
        A::Xor => B::BitXor,
        A::Or => B::BitOr,
    })
}

/// The value assigned by `v op= e`, in the type of `v`, lanes if `to_vec`.
fn assigned_value(
    state: &OutputState,
    v: &hir::Expr,
    op: &syntax::AssignmentOp,
    e: &hir::Expr,
    to_vec: bool,
) -> String {
    match assignment_binary_op(op) {
        None => ex_to(state, e, &v.ty, to_vec),
        Some(bop) => {
            let vec = is_vec(state, v) || is_vec(state, e);
            let code = binary_code(state, &bop, v, e, &v.ty, vec);
            convert(state, code, None, &v.ty, vec, &v.ty, to_vec)
        }
    }
}

/// `mask` as a lane mask (`I32`), for combining with `ret_mask`.
fn mask_lanes(state: &OutputState, mask: &hir::Expr) -> String {
    let code = ex(state, mask);
    if is_vec(state, mask) {
        code
    } else {
        promote(state, code, &Type::new(TypeKind::Bool))
    }
}

/// `ret_mask`, `I32` lanes when the function returns lanes.
fn ret_mask_type(state: &OutputState) -> &'static str {
    if state.return_vector {
        "I32"
    } else {
        "i32"
    }
}

fn emit_assignment(
    state: &OutputState,
    v: &hir::Expr,
    op: &syntax::AssignmentOp,
    e: &hir::Expr,
    top_level: bool,
) -> String {
    let is_output = hir::is_output(v, &state.hir).is_some();
    let is_scalar_var = !is_vec(state, v);
    let is_scalar_expr = !is_vec(state, e);
    let force_scalar = is_scalar_var && !is_scalar_expr;

    let stmt = if let Some(mask) = &state.mask {
        let is_scalar_mask = !is_vec(state, mask);
        let force_scalar_mask = is_scalar_var && is_scalar_expr && !is_scalar_mask;
        let use_ret = is_output && state.return_declared;
        let mask_code = if use_ret {
            if state.return_vector {
                format!("({}) & ret_mask", mask_lanes(state, mask))
            } else {
                format!("({}) & ret_mask", ex(state, mask))
            }
        } else {
            ex(state, mask)
        };
        let mask_vec = !is_scalar_mask || (use_ret && state.return_vector);
        if force_scalar || force_scalar_mask {
            // C++: if (mask[0]) { v = force_scalar(e); }
            let test = if mask_vec { format!("({})[0] != 0", mask_code) } else { mask_code };
            let value = assigned_value(state, v, op, e, false);
            format!("if {} {{ {}; }}", test, store(state, v, value))
        } else if mask_vec {
            let value = assigned_value(state, v, op, e, true);
            let old = convert(state, ex(state, v), Some(v), &v.ty, !is_scalar_var, &v.ty, true);
            state.require(format!("if_then_else(I32, {0}, {0})", type_str(state, &v.ty, false)));
            let ite = format!("{}({}, {}, {})", state.rt("glsl", "if_then_else"), mask_code, value, old);
            store(state, v, ite)
        } else {
            let value = assigned_value(state, v, op, e, !is_scalar_var);
            format!("if {} {{ {}; }}", mask_code, store(state, v, value))
        }
    } else if is_output && state.return_declared {
        if state.return_vector {
            // v = force_scalar?(if_then_else(ret_mask, v op e, v))
            let value = assigned_value(state, v, op, e, true);
            let old = convert(state, ex(state, v), Some(v), &v.ty, !is_scalar_var, &v.ty, true);
            state.require(format!("if_then_else(I32, {0}, {0})", type_str(state, &v.ty, false)));
            let ite = format!("{}(ret_mask, {}, {})", state.rt("glsl", "if_then_else"), value, old);
            let ite = convert(state, ite, None, &v.ty, true, &v.ty, !is_scalar_var);
            store(state, v, ite)
        } else {
            let value = assigned_value(state, v, op, e, !is_scalar_var);
            format!("if ret_mask != 0 {{ {}; }}", store(state, v, value))
        }
    } else {
        let value = assigned_value(state, v, op, e, !is_scalar_var);
        store(state, v, value)
    };

    if top_level {
        stmt
    } else {
        format!("{{ {}; {} }}", stmt, ex(state, v))
    }
}

/// Whether evaluating `e` calls something that borrows `self` mutably or uses `ctx`, so that it cannot be an
/// argument of a call that already holds such a borrow.
fn has_effectful_call(state: &OutputState, e: &hir::Expr) -> bool {
    let mut calls = Vec::new();
    collect_calls_expr(e, &mut calls);
    calls.iter().any(|c| {
        let sym = state.hir.sym(*c);
        match &sym.decl {
            hir::SymDecl::UserFunction(..) => {
                let i = state.info(*c);
                i.needs_ctx || i.mut_self
            }
            hir::SymDecl::NativeFunction(..) => {
                native_needs_ctx(&sym.name) || native_needs_fs(&sym.name) || sym.name == "swgl_stepInterp"
            }
            _ => false,
        }
    })
}

/// A call whose arguments were bound to temporaries first: `{ let _a0_ = ..; f(_a0_) }`.
struct Call {
    lets: Vec<String>,
    args: Vec<String>,
    after: Vec<String>,
}

impl Call {
    fn new() -> Self {
        Call { lets: Vec::new(), args: Vec::new(), after: Vec::new() }
    }

    fn finish(self, call: String, top_level: bool) -> String {
        if self.lets.is_empty() && self.after.is_empty() {
            return call;
        }
        let mut s = String::from("{ ");
        for l in &self.lets {
            s.push_str(l);
            s.push_str("; ");
        }
        if self.after.is_empty() {
            s.push_str(&call);
        } else {
            if top_level {
                s.push_str(&call);
                s.push_str("; ");
            } else {
                let _ = write!(s, "let _ret_ = {}; ", call);
            }
            for a in &self.after {
                s.push_str(a);
                s.push_str("; ");
            }
            if !top_level {
                s.push_str("_ret_");
            }
        }
        s.push_str(" }");
        s
    }
}

/// The signature a native call resolved to, the same search as the HIR's.
fn native_signature<'a>(fn_ty: &'a hir::FunctionType, args: &[hir::Expr]) -> Option<&'a hir::FunctionSignature> {
    let mut ret = None;
    let mut best_score = 0;
    'next_sig: for sig in &fn_ty.signatures {
        let mut score = 0;
        for (e, p) in args.iter().zip(sig.params.iter()) {
            if e.ty == *p {
                score += 1;
            } else if !can_implicitly_convert_to(&e.ty, p) {
                continue 'next_sig;
            }
        }
        if score >= best_score {
            ret = Some(sig);
            best_score = score;
            if best_score >= args.len() {
                break;
            }
        }
    }
    ret
}

fn can_implicitly_convert_to(src: &Type, dst: &Type) -> bool {
    // glsl-to-cxx's hir.rs rule, as one expression.
    use TypeKind::*;
    (src == &Type::new(Double) && dst == &Type::new(Float))
        || (dst == &Type::new(Double) && src == &Type::new(Float))
        || ((dst == &Type::new(Float) || dst == &Type::new(Double)) && src == &Type::new(Int))
        || ((dst == &Type::new(Vec2) || dst == &Type::new(DVec2)) && src == &Type::new(IVec2))
        || (dst == &Type::new(IVec2) && (src == &Type::new(Vec2) || src == &Type::new(DVec2)))
        || (src.kind == dst.kind && src.array_sizes == dst.array_sizes)
}

fn emit_call(
    state: &OutputState,
    expr: &hir::Expr,
    fun: &hir::FunIdentifier,
    args: &[hir::Expr],
    top_level: bool,
) -> String {
    let mut arg_mask: u32 = 0;
    for (idx, e) in args.iter().enumerate() {
        if is_vec(state, e) {
            arg_mask |= 1 << idx;
        }
    }

    let name = match fun {
        hir::FunIdentifier::Constructor(t) => {
            // An array constructor: `vec2[](a, b)` is `[a, b]`.
            let v = arg_mask != 0;
            let elem = Type::new(t.kind);
            let elems: Vec<String> = args.iter().map(|a| ex_to(state, a, &elem, v)).collect();
            return format!("[{}]", elems.join(", "));
        }
        hir::FunIdentifier::Identifier(name) => *name,
    };

    let sym = state.hir.sym(name);
    match &sym.decl {
        hir::SymDecl::NativeFunction(fn_ty, cxx_name, ret_class) => {
            emit_native(state, expr, name, &sym.name, fn_ty, *cxx_name, *ret_class, args, arg_mask, top_level)
        }
        hir::SymDecl::UserFunction(fd, _) => {
            let fd = fd.clone();
            drop(sym);
            emit_user_call(state, name, &fd, args, arg_mask, top_level)
        }
        hir::SymDecl::Struct(fields) => {
            // A struct constructor is a function named like the struct.
            let v = arg_mask != 0;
            let fname = if v { sym.name.clone() } else { format!("{}_scalar", sym.name) };
            let fields = fields.fields.clone();
            drop(sym);
            let a: Vec<String> = args.iter().zip(fields.iter()).map(|(a, f)| ex_to(state, a, &f.ty, v)).collect();
            format!("{}({})", fname, a.join(", "))
        }
        _ => panic!("bad identifier to function call"),
    }
}

#[allow(clippy::too_many_arguments)]
fn emit_native(
    state: &OutputState,
    expr: &hir::Expr,
    _sym: SymRef,
    name: &str,
    fn_ty: &hir::FunctionType,
    cxx_name: Option<&'static str>,
    ret_class: hir::RunClass,
    args: &[hir::Expr],
    arg_mask: u32,
    top_level: bool,
) -> String {
    if name == "texelFetchOffset" && args.len() >= 4 {
        if let Some((sampler, base, x, y)) = hir::get_texel_fetch_offset(&state.hir, &args[0], &args[1], &args[3]) {
            let base_sym = state.hir.sym(base);
            let sampler_sym = state.hir.sym(sampler);
            add_used_global(state, &sampler);
            if let hir::SymDecl::Global(..) = &base_sym.decl {
                add_used_global(state, &base);
            }
            return format!(
                "{}(self.{}, {}_{}_fetch, {}, {})",
                state.rt("texture", "texelFetchUnchecked"),
                sampler_sym.name,
                sampler_sym.name,
                base_sym.name,
                x,
                y,
            );
        }
    } else if name.starts_with("swgl_commitDithered") {
        state.used_fragcoord.set(state.used_fragcoord.get() | 1 | 2);
    }
    match name {
        // Macros in swgl_ext.h that work on the shader object.
        "swgl_stepInterp" => return "self.step_interp_inputs(4)".to_string(),
        "swgl_interpStep" => {
            if let hir::ExprKind::Variable(v) = &args[0].kind {
                return format!("self.interp_step.{}", state.hir.sym(*v).name);
            }
            panic!("swgl_interpStep takes a varying");
        }
        _ => {}
    }

    let rname = cxx_name.unwrap_or(name);
    let module = native_module(rname);
    // swgl_ext.h overloads the YUV commits by plane count (1, 2 or 3 sampler/uv/rect triples), which Rust cannot:
    // ext names the two- and three-plane forms `..YUV2` and `..YUV3`.
    let planes = match rname {
        "swgl_commitTextureLinearYUV" => (args.len() - 3) / 3,
        "swgl_commitTextureLinearColorYUV" => (args.len() - 4) / 3,
        _ => 1,
    };
    let rname = if planes > 1 { format!("{rname}{planes}") } else { rname.to_string() };
    let rname = state.rt(module, &rust_ident(&rname));
    let call_vec = if ret_class != hir::RunClass::Unknown { ret_class == hir::RunClass::Vector } else { arg_mask != 0 };
    let promote_args = !native_passthrough(name) && ret_class == hir::RunClass::Unknown;
    let sig = native_signature(fn_ty, args);
    let needs_ctx = native_needs_ctx(name);
    let needs_fs = native_needs_fs(name);
    let hoist = (needs_ctx || needs_fs) && args.iter().any(|a| has_effectful_call(state, a));

    let mut call = Call::new();
    let mut arg_types = Vec::new();
    for (i, a) in args.iter().enumerate() {
        let a_vec = is_vec(state, a);
        let code = if a.ty.kind.is_sampler() {
            ex(state, a)
        } else {
            let p = sig.and_then(|s| s.params.get(i).cloned()).unwrap_or_else(|| a.ty.clone());
            // Keep the argument's own type unless the overload needs an implicit conversion.
            let to = if p.kind != a.ty.kind && can_implicitly_convert_to(&a.ty, &p) { p } else { a.ty.clone() };
            // Bool selectors keep their run class: C++ has `mix(T, T, bvec4_scalar1)` & co.
            let to_vec = if promote_args && !a.ty.kind.is_bool() { call_vec } else { a_vec };
            arg_types.push(type_str(state, &to, !to_vec));
            ex_to(state, a, &to, to_vec)
        };
        if a.ty.kind.is_sampler() {
            arg_types.push(type_str(state, &a.ty, true));
        }
        if hoist {
            let t = state.tmp("a");
            call.lets.push(format!("let {} = {}", t, code));
            call.args.push(t);
        } else {
            call.args.push(code);
        }
    }
    if needs_ctx {
        arg_types.insert(0, "&mut RasterState".into());
    }
    if needs_fs {
        arg_types.push("&mut FragmentShaderState".into());
    }
    let ret = type_str(state, &expr.ty, !call_vec);
    state.require(format!("fn {}({}) -> {}", rname, arg_types.join(", "), ret));

    if name == "textureSize" && call.args.len() == 1 {
        // C++'s `textureSize(sampler2DRect)` has no LOD; the runtime has one `textureSize(s, lod)`, which ignores
        // the LOD as C++'s `textureSize(sampler2D, int)` does.
        call.args.push("0".to_string());
    }
    let code = if rname.starts_with("make_") && call.args.len() > 1 {
        // The C++ constructors overload on arity; the runtime's take a tuple.
        format!("{}(({}))", rname, call.args.join(", "))
    } else {
        let mut all = Vec::new();
        if needs_ctx {
            all.push("ctx".to_string());
        }
        all.append(&mut call.args);
        if needs_fs {
            all.push("&mut self.fs".to_string());
        }
        format!("{}({})", rname, all.join(", "))
    };
    call.finish(code, top_level)
}

fn emit_user_call(
    state: &OutputState,
    name: SymRef,
    fd: &hir::FunctionDefinition,
    args: &[hir::Expr],
    arg_mask: u32,
    top_level: bool,
) -> String {
    let mut cond_mask: u32 = 0;
    if (state.mask.is_some() || state.return_declared) && !fd.globals.is_empty() {
        cond_mask |= 1 << 31;
    }
    let mut param_mask: u32 = 0;
    let mut has_out = false;
    for (idx, param) in fd.prototype.parameters.iter().enumerate() {
        if let hir::FunctionParameterDeclaration::Named(qual, p) = param {
            if symbol_run_class(&state.hir.sym(p.sym).decl, arg_mask) == hir::RunClass::Vector {
                param_mask |= 1 << idx;
            }
            if let Some(hir::ParameterQualifier::InOut) | Some(hir::ParameterQualifier::Out) = qual {
                has_out = true;
                if state.mask.is_some() || state.return_declared {
                    cond_mask |= 1 << idx;
                }
            }
        }
    }
    let info = state.info(name);
    let hoist = has_out || args.iter().any(|a| has_effectful_call(state, a));
    // The callee goes on the dependency list before its arguments' callees, as in glsl-to-cxx (the order the
    // variants are written in, and so the `_cN_` numbering, follows it).
    let dep_key = (name, if cond_mask != 0 { param_mask | (1 << 31) } else { param_mask });
    {
        let mut deps = state.deps.borrow_mut();
        if !deps.contains(&dep_key) {
            deps.push(dep_key);
        }
    }

    let mut call = Call::new();
    for (idx, (param, e)) in fd.prototype.parameters.iter().zip(args.iter()).enumerate() {
        let (qual, p) = match param {
            hir::FunctionParameterDeclaration::Named(qual, p) => (qual, p),
            hir::FunctionParameterDeclaration::Unnamed(..) => panic!("unnamed parameter"),
        };
        let p_vec = param_mask & (1 << idx) != 0;
        match qual {
            Some(hir::ParameterQualifier::InOut) | Some(hir::ParameterQualifier::Out) => {
                let e_vec = is_vec(state, e);
                let global_root = match place_root(e) {
                    Some((s, swizzled)) => swizzled || matches!(state.hir.sym(s).decl, hir::SymDecl::Global(..)),
                    None => true,
                };
                if (!e_vec && p_vec) || global_root {
                    // C++ adapts a scalar argument of a vector parameter through a temporary and force_scalar;
                    // places on `self` or behind a swizzle go through a temporary too (copy in, copy out, which
                    // is GLSL's semantics), since `self` is borrowed by the call.
                    let t = format!("_arg{}_", idx);
                    let ty = type_name(state, &p.ty, !p_vec);
                    call.lets.push(format!("let mut {}: {} = {}", t, ty, ex_to(state, e, &p.ty, p_vec)));
                    let back = convert(state, t.clone(), None, &p.ty, p_vec, &e.ty, e_vec);
                    call.after.push(store(state, e, back));
                    call.args.push(format!("&mut {}", t));
                } else {
                    let place = match lvalue(state, e) {
                        LValue::Place(p) => p,
                        LValue::Swizzle(..) => unreachable!(),
                    };
                    call.args.push(format!("&mut {}", place));
                }
            }
            _ => {
                let code = ex_to(state, e, &p.ty, p_vec);
                if hoist {
                    let t = state.tmp("a");
                    call.lets.push(format!("let {} = {}", t, code));
                    call.args.push(t);
                } else {
                    call.args.push(code);
                }
            }
        }
    }

    let mut all = Vec::new();
    if info.needs_ctx {
        all.push("ctx".to_string());
    }
    all.append(&mut call.args);
    if cond_mask != 0 {
        let m = if let Some(mask) = &state.mask {
            if state.return_declared {
                format!("({}) & ret_mask", mask_lanes(state, mask))
            } else {
                mask_lanes(state, mask)
            }
        } else if state.return_declared {
            if state.return_vector {
                "ret_mask".to_string()
            } else {
                promote(state, "(ret_mask != 0)".to_string(), &Type::new(TypeKind::Bool))
            }
        } else {
            promote(state, "!0i32".to_string(), &Type::new(TypeKind::Int))
        };
        all.push(m);
    }
    let code = format!("self.{}({})", state.fn_name(dep_key.0, dep_key.1), all.join(", "));
    call.finish(code, top_level)
}

// ---- declarations -----------------------------------------------------------------------------------------------

fn show_initializer(state: &OutputState, i: &hir::Initializer, ty: &Type, vec: bool) -> String {
    match *i {
        hir::Initializer::Simple(ref e) => ex_to(state, e, ty, vec),
        hir::Initializer::List(ref list) => {
            let elem = Type::new(ty.kind);
            let items: Vec<String> = list.0.iter().map(|i| show_initializer(state, i, &elem, vec)).collect();
            format!("[{}]", items.join(", "))
        }
    }
}

/// A GLSL struct: the `_scalar` and the lane form, a constructor function for each (named like the struct, as
/// C++ spells a constructor call), `From<S_scalar> for S` (C++'s IMPLICIT converting constructor) and
/// `IfThenElse<S> for I32` (C++'s friend `if_then_else`).
fn write_struct(state: &OutputState, sym: SymRef) {
    let name = state.hir.sym(sym).name.clone();
    if state.structs.borrow().iter().any(|(n, _)| *n == name) {
        return;
    }
    let fields = match &state.hir.sym(sym).decl {
        hir::SymDecl::Struct(s) => s.fields.clone(),
        _ => panic!(),
    };
    let mut s = String::new();
    for scalar in [true, false] {
        let n = if scalar { format!("{}_scalar", name) } else { name.clone() };
        let _ = write!(s, "#[derive(Clone, Copy, Default)]\npub struct {} {{\n", n);
        for f in &fields {
            let _ = writeln!(s, "    pub {}: {},", f.name, type_name(state, &f.ty, scalar));
        }
        s.push_str("}\n");
        let params: Vec<String> =
            fields.iter().map(|f| format!("{}: {}", f.name, type_name(state, &f.ty, scalar))).collect();
        let inits: Vec<String> = fields.iter().map(|f| f.name.to_string()).collect();
        let _ = write!(
            s,
            "#[inline(always)]\npub fn {0}({1}) -> {0} {{\n    {0} {{ {2} }}\n}}\n",
            n,
            params.join(", "),
            inits.join(", ")
        );
    }
    let conv: Vec<String> = fields
        .iter()
        .map(|f| {
            let v = convert(state, format!("s.{}", f.name), None, &f.ty, false, &f.ty, true);
            format!("{}: {}", f.name, v)
        })
        .collect();
    let _ = write!(
        s,
        "impl From<{0}_scalar> for {0} {{\n    #[inline(always)]\n    fn from(s: {0}_scalar) -> {0} {{\n        \
         {0} {{ {1} }}\n    }}\n}}\n",
        name,
        conv.join(", ")
    );
    let ite: Vec<String> =
        fields.iter().map(|f| format!("{0}: {1}(c, t.{0}, e.{0})", f.name, state.rt("glsl", "if_then_else"))).collect();
    let _ = write!(
        s,
        "impl {2}<{0}> for I32 {{\n    type Output = {0};\n    #[inline(always)]\n    \
         fn if_then_else(self, t: {0}, e: {0}) -> {0} {{\n        let c = self;\n        {0} {{ {1} }}\n    }}\n}}\n\n",
        name,
        ite.join(", "),
        state.rt("glsl", "IfThenElse")
    );
    state.rt("glsl", "I32");
    state.structs.borrow_mut().push((name, s));
}

/// A declaration at global scope: struct definitions, the stage struct's fields (the C++ members), consts.
fn collect_global_declaration(state: &OutputState, d: &hir::Declaration) {
    match d {
        hir::Declaration::StructDefinition(sym) => write_struct(state, *sym),
        hir::Declaration::InitDeclaratorList(list) => {
            let d = &list.head;
            if let Some(ty_def) = d.ty_def {
                write_struct(state, ty_def);
            }
            let sym = state.hir.sym(d.name);
            let (storage, run_class) = match &sym.decl {
                hir::SymDecl::Global(storage, _, _, _) => (*storage, symbol_run_class(&sym.decl, 0)),
                _ => return,
            };
            let scalar = run_class == hir::RunClass::Scalar;
            let name = sym.name.clone();
            drop(sym);
            if !list.tail.is_empty() {
                panic!("several global declarators in one declaration ({})", name);
            }
            let member = match (state.kind, storage) {
                (_, hir::StorageClass::Const) => {
                    let ty = type_name(state, &d.ty, scalar);
                    let init = d.initializer.as_ref().expect("const without initializer");
                    let code = show_initializer(state, init, &d.ty, !scalar);
                    let item = if const_is_literal(state, d.name) {
                        format!("    pub const {}: {} = {};\n", name, ty, code)
                    } else {
                        format!("    #[inline(always)]\n    pub fn {}() -> {} {{\n        {}\n    }}\n", name, ty, code)
                    };
                    state.assoc.borrow_mut().push(item);
                    false
                }
                (_, hir::StorageClass::Uniform) | (_, hir::StorageClass::Sampler(_)) => false,
                (ShaderKind::Vertex, hir::StorageClass::Out) => !scalar,
                (ShaderKind::Fragment, hir::StorageClass::Out) | (_, hir::StorageClass::FragColor(_)) => false,
                (ShaderKind::Fragment, hir::StorageClass::In) => !scalar,
                _ => true,
            };
            if member {
                if d.initializer.is_some() {
                    panic!("global {} with an initializer", name);
                }
                let ty = type_name(state, &d.ty, scalar);
                state.fields.borrow_mut().push((rust_ident(&name), ty));
            }
        }
        _ => {}
    }
}

fn show_declaration(state: &mut OutputState, d: &hir::Declaration) {
    match *d {
        hir::Declaration::InitDeclaratorList(ref list) => {
            show_indent(state);
            let code = show_local_declaration(state, list);
            state.write(&code);
            state.write("\n");

            let base = list.head.name;
            let base_sym = state.hir.sym(base);
            if let hir::SymDecl::Local(..) = &base_sym.decl {
                let mut texel_fetches = state.texel_fetches.borrow_mut();
                while let Some(idx) = texel_fetches.iter().position(|&(_, b, _)| b == base) {
                    let (sampler, _, offsets) = texel_fetches.remove(idx);
                    let sampler_sym = state.hir.sym(sampler);
                    define_texel_fetch_ptr(state, &base_sym, &sampler_sym, &offsets);
                }
            }
        }
        hir::Declaration::StructDefinition(ref sym) => write_struct(state, *sym),
        _ => {}
    }
}

fn show_local_declaration(state: &OutputState, list: &hir::InitDeclaratorList) -> String {
    let d = &list.head;
    let sym = state.hir.sym(d.name);
    let vec = symbol_run_class(&sym.decl, state.vector_mask) == hir::RunClass::Vector;
    let name = rust_ident(&sym.name);
    drop(sym);
    if let Some(ty_def) = d.ty_def {
        write_struct(state, ty_def);
    }
    let ty = type_name(state, &d.ty, !vec);
    let mut s = match &d.initializer {
        Some(i) => format!("let mut {}: {} = {};", name, ty, show_initializer(state, i, &d.ty, vec)),
        None => format!("let mut {}: {} = Default::default();", name, ty),
    };
    for t in &list.tail {
        let n = rust_ident(t.ident.ident.as_str());
        match &t.initializer {
            Some(i) => {
                let _ = write!(s, " let mut {}: {} = {};", n, ty, show_initializer(state, i, &d.ty, vec));
            }
            None => {
                let _ = write!(s, " let mut {}: {} = Default::default();", n, ty);
            }
        }
    }
    s
}

fn define_texel_fetch_ptr(
    state: &OutputState,
    base_sym: &hir::Symbol,
    sampler_sym: &hir::Symbol,
    offsets: &hir::TexelFetchOffsets,
) {
    show_indent(state);
    let base = match &base_sym.decl {
        hir::SymDecl::Global(..) => format!("self.{}", base_sym.name),
        _ => base_sym.name.clone(),
    };
    writeln!(
        state,
        "let {}_{}_fetch = {}(self.{}, {}, {}, {}, {}, {});",
        sampler_sym.name,
        base_sym.name,
        state.rt("texture", "texelFetchPtr"),
        sampler_sym.name,
        base,
        offsets.min_x,
        offsets.max_x,
        offsets.min_y,
        offsets.max_y,
    );
}

