//! glsl-to-rust: WebRender's GLSL to vectorized Rust, forked from glsl-to-cxx 0.70.
//!
//! `hir.rs` (parse tree to typed HIR with scalar/vector run classes) is glsl-to-cxx's, with the changes listed at its
//! top. This file replaces glsl-to-cxx's C++ emitter. It walks the HIR the same way, in the same order, with the same
//! masks, variants and temporaries (`_c3_`, `ret_mask`, `_cond_mask_`, `<sampler>_<base>_fetch`), so the output reads
//! side by side with the C++ header of the same program. What C++ got from overloading and implicit conversion is
//! spelled out here from the HIR's types and run classes: lane promotions (`Float::from(x)`), `force_scalar`,
//! `if_then_else`, int-to-float conversions, `&mut` out parameters, one name per function variant. `README.md` has
//! the table.

#![allow(unknown_lints, mismatched_lifetime_syntaxes)]

extern crate glsl;

pub mod build;
// glsl-to-cxx's HIR, kept as it was written so it diffs against the original.
#[rustfmt::skip]
#[allow(clippy::all)]
mod hir;

